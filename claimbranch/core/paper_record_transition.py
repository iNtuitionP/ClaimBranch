"""Replayable unaccepted interpretation recording, retaining its whole review.

Legacy record commands can express this scientific effect. Merge explanation
policy cannot be flattened into those commands, and is deliberately excluded.
This object is a candidate calculation, never a receipt or an accepted log.
"""
from copy import deepcopy
from dataclasses import dataclass

from .paper_changes import AmendmentLineage, lineage_schema
from .paper_operation import REVIEW_V2
from .research_history import ResearchHistory
from .research_schema import HASH, array, command_schema, obj


TRANSITION = obj(schema={'const': 'claimbranch.paper-record-transition/v1'},
    review=REVIEW_V2, review_digest=HASH, source_history_digest=HASH,
    result_history_digest=HASH, commands=array(command_schema(3), 2, 1),
    origins=array(lineage_schema(), 64),
    authority={'const': 'unaccepted-record-transition'},
    authorization_verified={'const': False}, acceptance_available={'const': False},
    accepted_writes={'const': 0}, accepted_debts_created={'const': 0})


def transition_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:paper-record-transition:v1',
            '$comment': 'Generated by scripts/export_research_schema.py. Record only, not merge. '
                        'Runtime rederives exact commands, full review and owned origin registry, '
                        'replays scientific invariants and binds before/after manifest digests. '
                        'Canonical bound 256 KiB; imports and replay grant no accepted authority.',
            **deepcopy(TRANSITION)}


@dataclass(frozen=True)
class PaperRecordTransition:
    payload: bytes
    digest: str
    source_history: ResearchHistory
    history: ResearchHistory
    origins: tuple[AmendmentLineage, ...]

    @property
    def authorization_verified(self):
        return False

    @property
    def requires_authorization(self):
        return True
