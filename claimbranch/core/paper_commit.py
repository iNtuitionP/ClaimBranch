"""Bounded transaction effects awaiting authoritative sources and native consent.

The exact review is retained rather than translated into a legacy merge command.
These bytes describe conditional effects only: no receipt, accepted log, debt
transition, or imported authority is created by this format.
"""
from copy import deepcopy
from dataclasses import dataclass

from .paper_operation import REVIEW
from .research_schema import HASH, HEADS, ID, array, nullable, obj


DEBT_OPENING = obj(id=ID, kind={'enum': ['manuscript', 'understanding']},
    project_id=ID, episode_id=ID, cause_operation_id=ID, cause_review_digest=HASH,
    cause_main_head=ID, evidence_watermark={'type': 'integer', 'minimum': 0, 'maximum': 32},
    anchor_id=nullable(ID), manuscript_digest=nullable(HASH), topics_digest=nullable(HASH),
    status={'const': 'opens-if-accepted'})
COMMIT = obj(schema={'const': 'claimbranch.paper-commit-candidate/v1'},
    review=REVIEW, review_digest=HASH, resulting_heads=HEADS,
    debt_openings=array(DEBT_OPENING, 2), authority={'const': 'unaccepted-commit-candidate'},
    authorization_verified={'const': False}, acceptance_available={'const': False},
    accepted_writes={'const': 0}, accepted_debts_created={'const': 0})


def commit_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:paper-commit-candidate:v1',
            '$comment': ('Generated by scripts/export_research_schema.py. Conditional transaction effects, '
                         'not accepted state. The owning policy rederives exact review, heads and debt '
                         'openings. Imports/digests grant no authority. Canonical envelope limit 256 KiB.'),
            **deepcopy(COMMIT)}


@dataclass(frozen=True)
class PaperCommitCandidate:
    payload: bytes
    digest: str

    @property
    def requires_authorization(self):
        return True

    @property
    def authorization_verified(self):
        return False
