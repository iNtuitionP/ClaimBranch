"""Closed scientific fields for version-two disposable context projections.

Source references are descriptions, not retrieved artifacts or fidelity proof.
Structural parent IDs never imply a supports/challenges/qualifies relation.
"""
from copy import deepcopy

from .canonical import ContractError
from .research_schema import HASH, ID, METRIC, TEXT, array, normalize, nullable, obj


NODE_LIMIT = 16
EDGE_LIMIT = 32
FIELD_LIMIT = 10
BYTE_LIMIT = 65_536
BINDING = obj(ref={"enum": ["main", "alternative"]}, view_digest=HASH)
SOURCE = obj(reference=TEXT, availability={"const": "unverified"})
FIELDS = {
    "claim": {"statement": TEXT, "status": {"enum": ["proposed", "supported", "contested"]},
              "role": {"enum": ["thesis", "main", "subclaim"]}, "scope": nullable(TEXT),
              "parent_ids": array(ID, 3, unique=True)},
    "observation": {"statement": TEXT, "status": {"enum": ["confirmed", "corrected", "invalidated", "retracted"]},
                    "value": TEXT, "run_id": ID, "metric": METRIC, "conditions": TEXT, "source": SOURCE},
    "experiment-record": {"question": TEXT, "method": TEXT, "conditions": TEXT, "metric": METRIC,
                          "source": SOURCE, "status": {"const": "recorded"}},
    "experiment-plan": {"claim_id": ID, "objective": TEXT, "status": {"const": "planned"},
                        "conditions": TEXT, "metric": METRIC},
    "interpretation": {"statement": TEXT, "observation_ids": array(ID, 16, unique=True), "episode_id": ID},
    "draft": {"statement": nullable(TEXT), "rationale": nullable(TEXT),
              "origin": obj(ai_influenced={"enum": [True, False]}, contributions_digest=HASH)},
    "scientific-relation": {"source_id": ID, "target_id": ID,
                            "edge_type": {"enum": ["supports", "challenges", "qualifies"]}, "rationale": TEXT},
}
# A selected measurement must not hide its invalidation/retraction; a plan
# must remain visibly unrun. Required fields are requested, never silently added.
REQUIRED = {"observation": {"status"}, "experiment-plan": {"status"},
            "draft": {"origin"},
            "scientific-relation": set(FIELDS["scientific-relation"])}


def validate_fields(kind, fields):
    if kind not in FIELDS or type(fields) is not dict or not fields or not set(fields).issubset(FIELDS[kind]):
        raise ContractError("unknown paper context kind or field")
    return normalize(fields, obj(**{name: FIELDS[kind][name] for name in fields}))


def request_schema():
    return deepcopy({"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "urn:claimbranch:paper-context-request:v1",
            "$comment": "Generated by scripts/export_research_schema.py; explicit selection, no authority or transport.",
            **obj(schema_version={"type": "integer", "const": 1}, project_id=ID, episode_id=ID,
                  ref=BINDING["properties"]["ref"], view_digest=HASH,
                  purpose={"enum": ["compare-evidence", "critique-interpretation", "plan-experiment", "draft-manuscript"]},
                  selections=array(obj(record_id=ID, fields=array(ID, FIELD_LIMIT, 1, True)), NODE_LIMIT, 1),
                  scientific_edge_ids=array(ID, EDGE_LIMIT, unique=True))})


def fields_schema():
    """Export full reader projections; selected subsets are validated at runtime."""
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "urn:claimbranch:paper-context-fields:v2",
            "$comment": "Generated from core/paper_context.py; full pre-selection reader projections.",
            "oneOf": [obj(kind={"const": kind}, fields=obj(**deepcopy(fields))) for kind, fields in FIELDS.items()]}
