"""Versioned request for disposable paper amendments, never accepted commands."""
from copy import deepcopy
from dataclasses import asdict, dataclass

from .canonical import ContractError, canonical_bytes, decode, digest
from .research_schema import (CONTRIBUTION, HASH, ID, PAPER_LIMITS, TEXT,
                              array, normalize, nullable, obj, paper_payloads)
from .review import Contribution, Judgment


def amendment_schema():
    return deepcopy(paper_payloads()["record-interpretation"]["properties"]["changes"])


def request_schema():
    return deepcopy({"$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:claimbranch:paper-changes-request:v1",
        "$comment": "Generated by scripts/export_research_schema.py; upsert preview only, no history mutation.",
        **obj(schema_version={"type": "integer", "const": 1}, project_id=ID, episode_id=ID,
              ref={"enum": ["main", "alternative"]}, view_digest=HASH, draft_id=ID,
              draft_revision={"type": "integer", "minimum": 0, "maximum": 2**53 - 1},
              amendments=amendment_schema(), selected_ids=array(ID, PAPER_LIMITS["changes"], 1, True))})


@dataclass(frozen=True)
class PaperDraftProjection:
    payload: bytes
    digest: str


@dataclass(frozen=True)
class PaperChangesPreview:
    payload: bytes
    digest: str


def lineage_schema(version=1):
    """Source snapshots may be unfinished; provenance is not a completed reason."""
    source = obj(project_id=ID, episode_id=ID, text=nullable(TEXT), rationale=nullable(TEXT),
                 history=array(CONTRIBUTION, 8))
    revision = obj(amendment=amendment_schema()['items'], sources=array(source, 8, unique=True),
                   parent_digest=nullable(HASH))
    if type(version) is not int or version not in (1, 2):
        raise ContractError('unknown amendment origin version')
    if version == 2:
        from .paper_proposals import ITEM
        origin = obj(proposal_id=ID, request_id=ID, request_digest=HASH, context_digest=HASH,
                     response_digest=HASH, trace_digest=HASH, item=ITEM, item_digest=HASH,
                     item_bindings=array(obj(item_id=ID, record_id=ID), 64, 1))
        revision['properties'].update(proposal_origin=nullable(origin))
        revision['required'].append('proposal_origin')
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': f'urn:claimbranch:paper-amendment-lineage:v{version}',
            '$comment': ('Generated by scripts/export_research_schema.py. Candidate origin only. Runtime verifies '
                         'canonical NFC JSON, the 256 KiB envelope, fixed record identity, parent and contribution '
                         'chains. Restore does not verify adoption or source authority.'),
            **obj(schema={'const': f'claimbranch.paper-amendment-lineage/v{version}'}, project_id=ID,
                  episode_id=ID, revisions=array(revision, 8, 1),
                  authority={'const': 'unaccepted-origin'}, authorization_verified={'const': False})}


@dataclass(frozen=True)
class AmendmentLineage:
    """Append-only candidate revisions, not a substitute for owned provider traces."""
    payload: bytes

    def __post_init__(self):
        value = normalize(decode(self.payload), {'oneOf': [lineage_schema(), lineage_schema(2)]})
        if canonical_bytes(value) != self.payload:
            raise ContractError('amendment lineage requires canonical bytes')
        parent, identity = None, None
        for position, revision in enumerate(value['revisions']):
            record = revision['amendment']
            if identity is None:
                identity = (record['id'], record['kind'])
            if (record['id'], record['kind']) != identity or revision['parent_digest'] != parent:
                raise ContractError('amendment identity or revision chain changed')
            for source in revision['sources']:
                if source['project_id'] != value['project_id']:
                    raise ContractError('amendment source belongs to another project')
                Judgment(source['project_id'], source['episode_id'], source['text'], source['rationale'],
                         tuple(Contribution(**item) for item in source['history']))
            origin = revision.get('proposal_origin')
            if origin:
                if position and origin['item']['action'] == 'create':
                    raise ContractError('A created proposal item cannot overwrite an earlier kept identity')
                if origin['item_digest'] != digest(origin['item']) or origin['item']['kind'] != record['kind']:
                    raise ContractError('proposal item identity or kind differs from its origin')
                if origin['item']['action'] == 'edit' and origin['item']['target_id'] != record['id']:
                    raise ContractError('proposal edit changed its scientific identity')
                bindings = origin['item_bindings']
                if (len({b['item_id'] for b in bindings}) != len(bindings)
                        or len({b['record_id'] for b in bindings}) != len(bindings)
                        or {b['item_id']: b['record_id'] for b in bindings}.get(origin['item']['id']) != record['id']):
                    raise ContractError('proposal item mapping changed its scientific identity')
            parent = digest(revision)

    @classmethod
    def start(cls, project_id, episode_id, amendment, *, sources=(), proposal_origin=None, version=None):
        version = (2 if proposal_origin else 1) if version is None else version
        lineage_schema(version)
        if proposal_origin is not None and version != 2:
            raise ContractError('Typed item origin requires version two lineage')
        return cls(canonical_bytes({'schema': f'claimbranch.paper-amendment-lineage/v{version}',
            'project_id': project_id, 'episode_id': episode_id,
            'revisions': [{'amendment': amendment, 'sources': _source_values(sources), 'parent_digest': None,
                           **({'proposal_origin': proposal_origin} if version == 2 else {})}],
            'authority': 'unaccepted-origin', 'authorization_verified': False}))

    @classmethod
    def restore(cls, raw):
        return cls(raw)

    def revise(self, amendment, *, sources=(), proposal_origin=None):
        value = decode(self.payload)
        source_values = _source_values(sources)
        record = normalize(amendment, amendment_schema()['items'])
        if proposal_origin and value['schema'].endswith('/v1'):
            raise ContractError('legacy lineage cannot be relabeled as owned typed adoption')
        if record == value['revisions'][-1]['amendment'] and not source_values and proposal_origin is None:
            return self
        if len(value['revisions']) >= 8:
            raise ContractError('Candidate origin has eight kept revisions; existing content and origin are retained')
        value['revisions'].append({'amendment': record, 'sources': source_values,
                                   'parent_digest': digest(value['revisions'][-1]),
                                   **({'proposal_origin': proposal_origin} if value['schema'].endswith('/v2') else {})})
        return AmendmentLineage(canonical_bytes(value))

    @property
    def amendment(self):
        return decode(self.payload)['revisions'][-1]['amendment']

    @property
    def digest(self):
        return digest(decode(self.payload))

    @property
    def ai_influenced(self):
        return any(revision.get('proposal_origin') for revision in decode(self.payload)['revisions']) or any(item['contributor'] == 'ai'
                   for revision in decode(self.payload)['revisions']
                   for source in revision['sources'] for item in source['history'])


def _source_values(sources):
    if type(sources) is not tuple or len(sources) > 8 or any(type(s) is not Judgment for s in sources):
        raise ContractError('bounded typed amendment source judgments required')
    return [asdict(source) for source in sources]
