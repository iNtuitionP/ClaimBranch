"""Finite candidate review policy. No receipts, accepted writes or comprehension grades.

The legacy v1–v3 seal_review policy is unchanged. These values must be bound to
an exact new command/review version before a protected gateway can consume them.
"""
from copy import deepcopy
from dataclasses import dataclass

from .canonical import ContractError
from .research_schema import HASH, ID, TEXT, array, nullable, obj


RULES = 'claimbranch.paper-review-policy/v1'
TOPIC_RULES = 'claimbranch.understanding-topics/v1'
_ACTIONS = {'capture-draft': ('low', None),
            'record-interpretation': ('medium', 'alternative'),
            'apply-selected-merge': ('high', 'main')}


def requirements(action, *, ai_influenced):
    if type(action) is not str or action not in _ACTIONS or type(ai_influenced) is not bool:
        raise ContractError('unknown finite review action or AI influence')
    impact, target = _ACTIONS[action]
    requirement = ('none' if impact == 'low' else
                   'contextual-explanation' if impact == 'high' and ai_influenced else 'rationale')
    return impact, target, requirement


TOPIC = obj(id=ID, kind={'enum': ['claim-scope', 'evidence-interpretation',
                                 'followup-experiment', 'manuscript-consequence']},
            prompt=TEXT, node_ids=array(ID, 128, 1, True), relation_ids=array(ID, 64, unique=True),
            cause_digest=HASH, rules_version={'const': TOPIC_RULES})
SELECTION = obj(selected=array(ID, 64, unique=True), required=array(ID, 64, unique=True),
                omitted=array(ID, 64, unique=True), existing_references=array(ID, 128, unique=True),
                evidence_references=array(ID, 32, unique=True))
ASSESSMENT = obj(schema={'const': 'claimbranch.paper-review-assessment/v1'},
    rules_version={'const': RULES}, project_id=ID, episode_id=ID,
    action={'enum': list(_ACTIONS)}, impact={'enum': ['low', 'medium', 'high']},
    target_ref=nullable({'enum': ['alternative', 'main']}), source_ref={'enum': ['main', 'alternative']},
    requirement={'enum': ['none', 'rationale', 'contextual-explanation']},
    history_digest=HASH, view_digest=HASH, science_digest=HASH, selection=SELECTION,
    judgment_digest=nullable(HASH), source_judgment_digests=array(HASH, 8, unique=True),
    rationale=nullable(TEXT), inherited_ai={'enum': [False, True]}, ai_influenced={'enum': [False, True]},
    lineages=array(obj(record_id=ID, digest=HASH), 64, unique=True), topics=array(TOPIC, 3), topics_digest=HASH,
    authority={'const': 'unaccepted-assessment'}, authorization_verified={'const': False},
    acceptance_available={'const': False})
ENTRY = obj(topic_id=ID, text={**TEXT, 'minLength': 0}, reuse_rationale={'enum': [False, True]})
DECISION = obj(schema={'const': 'claimbranch.paper-review-decision/v1'}, assessment_digest=HASH,
    disposition={'enum': ['not-required', 'answered', 'deferred', 'not-now']}, entries=array(ENTRY, 3),
    understanding_debt={'enum': ['none', 'opens-if-accepted']},
    authority={'const': 'unaccepted-review'}, authorization_verified={'const': False},
    acceptance_available={'const': False})


def _schema(name, value):
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': f'urn:claimbranch:{name}:v1',
            '$comment': ('Generated by scripts/export_research_schema.py. Candidate only. Runtime derives '
                         'policy and context from owned history/lineage and rechecks exact freshness; '
                         'schema validation alone cannot grant acceptance or verify source bindings.'),
            **deepcopy(value)}


def assessment_schema():
    return _schema('paper-review-assessment', ASSESSMENT)


def decision_schema():
    return _schema('paper-review-decision', DECISION)


@dataclass(frozen=True)
class ReviewAssessment:
    payload: bytes
    digest: str
