"""Exact candidate operations and reviews, separate from v1–v3 history commands.

These formats retain policy and origins which legacy commands cannot express.
Only the owning application can rederive their scientific bindings. Neither a
deserialized value nor a matching digest verifies acceptance or authorization.
"""
from copy import deepcopy
from dataclasses import dataclass

from .canonical import ContractError, integer
from .paper_changes import amendment_schema, lineage_schema
from .research_schema import HASH, HEADS, ID, JUDGMENT, array, nullable, obj
from .review_policy import ASSESSMENT, DECISION


TIME = {'type': 'integer', 'minimum': 0, 'maximum': 253402300799}
UTC = {'type': 'string', 'format': 'date-time', 'minLength': 20, 'maxLength': 20,
       'pattern': '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$'}
EFFECTS = {
    'record-interpretation': obj(branch_operation_id=nullable(ID),
                                 changes=amendment_schema(), judgment=JUDGMENT),
    'apply-selected-merge': obj(selected_ids=array(ID, 64, 1, True),
                                changes=amendment_schema(), judgment=JUDGMENT),
}
OPERATION = {'oneOf': [obj(schema={'const': 'claimbranch.paper-operation/v1'},
    id=ID, project_id=ID, episode_id=ID, action={'const': action}, created_at=UTC,
    expected_heads=HEADS, evidence_watermark={'type': 'integer', 'minimum': 0, 'maximum': 32},
    source_history_digest=HASH, assessment_digest=HASH, decision_digest=HASH,
    provenance_digest=HASH, effect=effect) for action, effect in EFFECTS.items()]}
PREPARATION = obj(action={'enum': list(EFFECTS)}, ref={'enum': ['main', 'alternative']},
    amendment_ids=array(ID, 64, unique=True), selected_ids=array(ID, 64, 1, True), judgment=nullable(JUDGMENT))
REVIEW_V1 = obj(schema={'const': 'claimbranch.paper-operation-review/v1'},
    operation=OPERATION, operation_digest=HASH, assessment=ASSESSMENT, decision=DECISION,
    lineages=array(lineage_schema(), 64), source_judgments=array(JUDGMENT, 8), preparation=PREPARATION,
    manuscript_digest=HASH, session_nonce=ID, sealed_at=TIME, expires_at=TIME,
    parent_review_digest=nullable(HASH), authority={'const': 'unaccepted-review'},
    authorization_verified={'const': False}, acceptance_available={'const': False})
REVIEW_V2 = deepcopy(REVIEW_V1)
REVIEW_V2['properties']['schema'] = {'const': 'claimbranch.paper-operation-review/v2'}
REVIEW_V2['properties']['origin_registry_digest'] = HASH
REVIEW_V2['properties']['operation'] = deepcopy(next(
    branch for branch in OPERATION['oneOf']
    if branch['properties']['action']['const'] == 'record-interpretation'))
REVIEW_V2['required'].append('origin_registry_digest')
REVIEW = {'oneOf': [REVIEW_V1, REVIEW_V2]}


def _schema(name, body):
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': f'urn:claimbranch:{name}:v1',
            '$comment': ('Generated by scripts/export_research_schema.py. Candidate only; canonical NFC JSON '
                         'is bounded to 256 KiB and a 300-second lifetime. Runtime rederives exact effects, '
                         'policy and origins from owned state. Schema/digest checks confer no authority.'),
            **deepcopy(body)}


def operation_schema():
    return _schema('paper-operation', OPERATION)


def review_schema(version=1):
    if type(version) is not int or version not in (1, 2):
        raise ContractError('unsupported operation review version')
    value = _schema('paper-operation-review', REVIEW_V1 if version == 1 else REVIEW_V2)
    value['$id'] = f'urn:claimbranch:paper-operation-review:v{version}'
    return value


def check_lifetime(sealed_at, expires_at, now):
    for value in (sealed_at, expires_at, now):
        integer(value, 0, TIME['maximum'])
    if not sealed_at <= now < expires_at <= sealed_at + 300:
        raise ContractError('operation review is expired or has an invalid lifetime')


@dataclass(frozen=True)
class PaperOperationReview:
    payload: bytes
    digest: str


@dataclass(frozen=True)
class PaperOperationCandidate:
    payload: bytes
    digest: str
    review_digest: str

    @property
    def requires_authorization(self):
        return True

    @property
    def authorization_verified(self):
        return False
