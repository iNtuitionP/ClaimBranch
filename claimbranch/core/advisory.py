"""Bounded readable advice; no graph item, action or scientific authority."""
from copy import deepcopy
from dataclasses import dataclass

from .canonical import ContractError, canonical_bytes, decode
from .paper_proposals import _controls
from .research_schema import HASH, ID, TEXT, array, normalize, obj


PROMPT = {**TEXT, 'maxLength': 4096, 'x-utf8-maxBytes': 4096}
PREVIOUS = obj(request_id=ID, prompt=PROMPT, text=TEXT,
               context_digest=HASH, reply_digest=HASH)
DISCUSSION = obj(prompt=PROMPT, previous=array(PREVIOUS, 2))
ADVICE = obj(schema={'const': 'claimbranch.provider-advice/v1'},
             status={'const': 'ok'}, text=TEXT)


def discussion_input(value):
    value = normalize(value, DISCUSSION)
    if not value['prompt'].strip() or _controls(value):
        raise ContractError('Discussion requires a nonblank question without terminal controls')
    ids = [message['request_id'] for message in value['previous']]
    if len(set(ids)) != len(ids):
        raise ContractError('Choose each earlier response once')
    return value


def advice_result_schema():
    return deepcopy({'$schema': 'https://json-schema.org/draft/2020-12/schema',
        '$id': 'urn:claimbranch:provider-advice:v1',
        '$comment': 'Generated by scripts/export_research_schema.py. Plain text is normalized locally; '
                    'this envelope contains no executable action or graph item.', **ADVICE})


def advice_from_text(raw):
    if type(raw) is not bytes or len(raw) > 16384:
        raise ContractError('Advisory text exceeds its 16384-byte limit')
    try:
        text = raw.decode('utf-8')
    except UnicodeError:
        raise ContractError('Advisory text must be UTF-8') from None
    value = normalize({'schema': 'claimbranch.provider-advice/v1', 'status': 'ok', 'text': text}, ADVICE)
    if not value['text'].strip() or _controls(value):
        raise ContractError('Advisory text is empty or contains terminal controls')
    return value


def checked_advice(raw):
    value = normalize(decode(raw), ADVICE)
    checked = advice_from_text(value['text'].encode('utf-8'))
    if canonical_bytes(checked) != raw:
        raise ContractError('Retained advice requires canonical bytes')
    return checked


@dataclass(frozen=True)
class AdvisoryReply:
    """Owned reading material; deliberately has no item or staging interface."""
    payload: bytes
