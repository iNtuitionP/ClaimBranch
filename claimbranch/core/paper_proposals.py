"""Closed, scoped typed suggestions; no allocation, adoption or scientific write.

Only explicitly selected context and response-local item references are legal.
Validation proves a bounded proposal, not source fidelity or a complete graph:
the eventual selected staging batch must still pass the existing domain checks.
"""
from .graph_vocabulary import SCIENTIFIC_EDGE_TYPES
from copy import deepcopy
from dataclasses import dataclass

from .canonical import ContractError, canonical_bytes, decode
from .research_schema import ID, METRIC, PAPER_LIMITS, TEXT, array, normalize, nullable, obj


RESULT_BYTE_LIMIT = 65_536
ITEM_LIMIT = PAPER_LIMITS['changes']
KINDS = ('claim', 'interpretation', 'scientific-edge', 'experiment-plan')
PURPOSE_KINDS = {purpose: KINDS for purpose in
                 ('compare-evidence', 'critique-interpretation', 'plan-experiment')}
CONTEXT_KIND = {'scientific-relation': 'scientific-edge'}
REFERENCE = obj(domain={'enum': ['context', 'item']}, id=ID)
BODIES = {
    'claim': obj(role={'enum': ['main', 'subclaim']}, statement=TEXT, scope=TEXT,
                 parent_ids=array(REFERENCE, 3, 1, True)),
    'interpretation': obj(statement=TEXT, observation_ids=array(REFERENCE, 16, unique=True)),
    'scientific-edge': obj(source_id=REFERENCE, target_id=REFERENCE,
        edge_type={'enum': list(SCIENTIFIC_EDGE_TYPES)}, rationale=TEXT),
    'experiment-plan': obj(claim_id=REFERENCE, objective=TEXT, status={'const': 'planned'},
                           conditions=TEXT, metric=METRIC),
}
ITEM = {'oneOf': [obj(id=ID, action={'enum': ['create', 'edit']}, kind={'const': kind},
                      target_id=nullable(ID), body=body) for kind, body in BODIES.items()]}


def result_schema():
    return deepcopy({'$schema': 'https://json-schema.org/draft/2020-12/schema',
        '$id': 'urn:claimbranch:provider-result:v2',
        '$comment': ('Generated by scripts/export_research_schema.py. Non-authoritative typed output. '
            'Runtime additionally checks status/content, exact selected references, kind/identity, '
            'role, cycles/depth, per-kind limits, terminal controls and the 65536-byte response bound. '
            'New scientific IDs are allocated only by later application-owned staging.'),
        **obj(schema={'const': 'claimbranch.provider-result/v2'}, status={'enum': ['ok', 'refused', 'failed']},
              critique=nullable(TEXT), items=array(ITEM, ITEM_LIMIT))})


def _references(item):
    body = item['body']
    return [body[name] for name in ('source_id', 'target_id', 'claim_id') if name in body] + \
        body.get('parent_ids', []) + body.get('observation_ids', [])


def _acyclic(outgoing):
    visiting, depths = set(), {}

    def visit(key):
        if key in visiting:
            raise ContractError('cyclic proposal dependency or claim relation')
        if key in depths:
            return depths[key]
        visiting.add(key)
        depth = 1 + max((visit(other) for other in outgoing.get(key, ())), default=0)
        visiting.remove(key)
        if depth > PAPER_LIMITS['depth']:
            raise ContractError('proposal dependency or claim depth exceeded')
        depths[key] = depth
        return depth

    for key in outgoing:
        visit(key)


def _controls(value):
    if isinstance(value, str):
        return any((ord(c) < 32 and c not in '\n\t') or 127 <= ord(c) <= 159
                   or 0x202a <= ord(c) <= 0x202e or 0x2066 <= ord(c) <= 0x2069
                   or ord(c) in (0x200e, 0x200f, 0x2028, 0x2029) for c in value)
    if isinstance(value, dict):
        return any(_controls(child) for child in value.values())
    if isinstance(value, list):
        return any(_controls(child) for child in value)
    return False


def provider_typed_result(raw, context):
    """Validate v2 against the dispatched context, never provider-supplied rows."""
    from .context import ContextBundle, compile_context
    if type(context) is not ContextBundle or context.selection.schema_version != 2:
        raise ContractError('typed suggestions require compiled paper context v2')
    if compile_context(context.records, context.selection) != context:
        raise ContractError('typed proposal context or digest changed')
    if context.selection.purpose not in PURPOSE_KINDS:
        raise ContractError('manuscript drafting stays on the existing text-only route')
    if type(raw) is not bytes or len(raw) > RESULT_BYTE_LIMIT:
        raise ContractError('bounded typed provider result bytes required')
    value = normalize(decode(raw), result_schema())
    if len(canonical_bytes(value)) > RESULT_BYTE_LIMIT or _controls(value):
        raise ContractError('typed response exceeds its byte limit or contains terminal controls')
    if value['status'] != 'ok':
        if value['critique'] is not None or value['items']:
            raise ContractError('refusal/failure cannot supply substitute suggestions')
        return value
    if value['critique'] is None and not value['items']:
        raise ContractError('a successful response requires critique or suggestions')
    selected = {row['id']: row for row in decode(context.payload)['records']}
    items, edits = {}, set()
    for item in value['items']:
        if item['id'] in items or item['kind'] not in PURPOSE_KINDS[context.selection.purpose]:
            raise ContractError('duplicate item identity or unsupported task/kind')
        items[item['id']] = item
        target = item['target_id']
        if item['action'] == 'create':
            if target is not None:
                raise ContractError('creation cannot supply a scientific record identity')
        else:
            source = selected.get(target)
            if (not source or CONTEXT_KIND.get(source['kind'], source['kind']) != item['kind']
                    or target in edits):
                raise ContractError('edit requires one matching explicitly selected target')
            if source['kind'] == 'claim' and source['fields'].get('role') not in ('main', 'subclaim'):
                raise ContractError('claim edits require a selected role; thesis editing is unavailable')
            if source['kind'] == 'interpretation' and source['fields'].get('episode_id') != context.selection.episode_id:
                raise ContractError('interpretation edit must disclose its current episode origin')
            edits.add(target)
    limits = {'claim': PAPER_LIMITS['claims'] - 1, 'interpretation': 1,
              'scientific-edge': PAPER_LIMITS['edges'], 'experiment-plan': PAPER_LIMITS['plans']}
    for kind, maximum in limits.items():
        if sum(item['kind'] == kind for item in items.values()) > maximum:
            raise ContractError('typed suggestion kind exceeds its finite limit')

    def resolve(ref, kinds):
        if ref['domain'] == 'context' and ref['id'] in edits:
            raise ContractError('reference a proposed edit by its item id, not its old context identity')
        source = (selected if ref['domain'] == 'context' else items).get(ref['id'])
        if not source or CONTEXT_KIND.get(source['kind'], source['kind']) not in kinds:
            raise ContractError('unknown, unselected or wrong-kind proposal reference')
        if ref['domain'] == 'context':
            return ('context', ref['id']), source['kind'], source['fields']
        key = ('context', source['target_id']) if source['action'] == 'edit' else ('item', source['id'])
        return key, source['kind'], source['body']

    dependencies, structural, scientific = {}, {}, {}
    # Inspect only selected fields. Unselected neighbors are neither fetched nor
    # silently certified; staging must recheck the complete current graph later.
    for row in selected.values():
        if row['id'] in edits:
            continue
        key, body = ('context', row['id']), row['fields']
        if row['kind'] == 'claim':
            structural[key] = {('context', parent) for parent in body.get('parent_ids', [])
                               if parent in selected and selected[parent]['kind'] == 'claim'}
        elif row['kind'] == 'scientific-relation' and selected[body['source_id']]['kind'] == 'claim':
            scientific.setdefault(('context', body['source_id']), set()).add(('context', body['target_id']))
    for item in items.values():
        dependencies[item['id']] = {ref['id'] for ref in _references(item) if ref['domain'] == 'item'}
        key = ('context', item['target_id']) if item['action'] == 'edit' else ('item', item['id'])
        body = item['body']
        if item['kind'] == 'claim':
            parents = [resolve(ref, ('claim',)) for ref in body['parent_ids']]
            roles = [fields.get('role') for _, _, fields in parents]
            if ((body['role'] == 'main' and (len(parents) != 1 or roles != ['thesis']))
                    or (body['role'] == 'subclaim' and any(role not in ('main', 'subclaim') for role in roles))):
                raise ContractError('claim role requires explicitly selected compatible parent roles')
            structural[key] = {parent for parent, _, _ in parents}
        elif item['kind'] == 'interpretation':
            for ref in body['observation_ids']:
                resolve(ref, ('observation',))
        elif item['kind'] == 'experiment-plan':
            resolve(body['claim_id'], ('claim',))
        else:
            source, kind, _ = resolve(body['source_id'], ('claim', 'observation', 'interpretation'))
            target, _, _ = resolve(body['target_id'], ('claim',))
            if source == target:
                raise ContractError('self-support or self-challenge is invalid')
            if kind == 'claim':
                scientific.setdefault(source, set()).add(target)
    for graph in (dependencies, structural, scientific):
        _acyclic(graph)
    return value


@dataclass(frozen=True)
class TypedProposal:
    """Broker-owned response metadata, not an adoption capability or authority."""
    id: str
    project_id: str
    episode_id: str
    request_digest: str
    context_digest: str
    trace_digest: str
    payload: bytes


def provider_edit_result(raw, context):
    """Explicit small edit; empty items plus critique asks for clarification."""
    value = provider_typed_result(raw, context)
    if len(value['items']) > 4:
        raise ContractError('An explicit edit permits at most four dependent items')
    return value
