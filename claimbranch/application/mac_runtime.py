"""Explicit source-built Mac runtime preflight, not approval or a trust root.

A separately retained build pin is mandatory; the adjacent manifest cannot
vouch for itself. Local ad-hoc code identity is not publisher identity, human
presence, a protected store, or confinement of an unrestricted same-user process.
"""
from contextlib import contextmanager
from copy import deepcopy
import hashlib
import os
from pathlib import Path
import re
import selectors
import signal
import stat
import subprocess
import sys
import tempfile
import time

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest_text
from claimbranch.core.research_schema import HASH, normalize, obj


ROLES = ('broker', 'gateway')
SOURCE = Path(__file__).with_name('native') / 'RuntimeIdentity.swift'
MAX_BINARY = 4 * 1024 * 1024
ENTRY = obj(binary_sha256=HASH, code_hash={'type': 'string', 'minLength': 40, 'maxLength': 40,
                                         'pattern': '^[0-9a-f]{40}$'})
MANIFEST = obj(schema={'const': 'claimbranch.mac-runtime-build/v1'}, source_sha256=HASH,
               broker=ENTRY, gateway=ENTRY,
               authorization_verified={'const': False}, protected_acceptance_available={'const': False})


def runtime_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:mac-runtime-build:v1',
            '$comment': 'Generated by scripts/export_research_schema.py. Exact build metadata only. '
                        'Runtime also requires an independently retained SHA-256 pin, canonical bytes, '
                        'private files, exact binary hashes, signatures and dynamic self checks. No authority.',
            **deepcopy(MANIFEST)}


def _hash(raw):
    return hashlib.sha256(raw).hexdigest()


def _identifier(role):
    return 'org.claimbranch.local-runtime.' + role


def _environment():
    # No inherited DYLD, PYTHON, developer-tool, provider or credential values.
    return {'PATH': '/usr/bin:/bin', 'LC_ALL': 'C', 'TZ': 'UTC'}


def _run(arguments, *, cwd, timeout=15, limit=65536, temporary=None, input_bytes=None, cancel_event=None):
    """Drain both pipes with one deadline and a bounded aggregate response."""
    if input_bytes is not None and (type(input_bytes) is not bytes or len(input_bytes) > 294912):
        raise ContractError('native runtime input exceeds its bound')
    process = None
    input_closed_early = False
    try:
        environment = _environment()
        if temporary is not None:
            environment['TMPDIR'] = str(temporary)
        process = subprocess.Popen(arguments, cwd=cwd, env=environment,
                                   stdin=subprocess.PIPE if input_bytes is not None else subprocess.DEVNULL, start_new_session=True,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        output = {'stdout': bytearray(), 'stderr': bytearray()}
        deadline = time.monotonic() + timeout
        with selectors.DefaultSelector() as selected:
            selected.register(process.stdout, selectors.EVENT_READ, 'stdout')
            selected.register(process.stderr, selectors.EVENT_READ, 'stderr')
            offset = 0
            if input_bytes:
                os.set_blocking(process.stdin.fileno(), False)
                selected.register(process.stdin, selectors.EVENT_WRITE, 'stdin')
            elif process.stdin is not None:
                process.stdin.close()
            while selected.get_map():
                if cancel_event is not None and cancel_event.is_set():
                    raise ContractError('native runtime command cancelled')
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise ContractError('native runtime command timed out')
                for key, _ in selected.select(min(remaining, .1) if cancel_event is not None else remaining):
                    if key.data == 'stdin':
                        try:
                            offset += os.write(key.fileobj.fileno(), input_bytes[offset:offset + 4096])
                        except BlockingIOError:
                            continue
                        except BrokenPipeError:
                            input_closed_early = True
                            selected.unregister(key.fileobj)
                            key.fileobj.close()
                            continue
                        if offset == len(input_bytes):
                            selected.unregister(key.fileobj)
                            key.fileobj.close()
                        continue
                    raw = os.read(key.fileobj.fileno(), 4096)
                    if not raw:
                        selected.unregister(key.fileobj)
                    else:
                        output[key.data].extend(raw)
                        if sum(map(len, output.values())) > limit:
                            raise ContractError('native runtime output exceeds its bound')
            # Observe without reaping: the reserved PID prevents cleanup from
            # signalling an unrelated process group after PID reuse.
            while os.waitid(os.P_PID, process.pid, os.WEXITED | os.WNOWAIT | os.WNOHANG) is None:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise ContractError('native runtime command timed out')
                time.sleep(min(0.01, remaining))
    except (OSError, subprocess.SubprocessError):
        raise ContractError('native runtime command is unavailable') from None
    finally:
        if process is not None:
            cleanup_failed = False
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            except PermissionError:
                # Darwin returns EPERM for a group containing only an exited,
                # unreaped child. Verify that state before accepting no signal.
                if os.waitid(os.P_PID, process.pid, os.WEXITED | os.WNOWAIT | os.WNOHANG) is None:
                    cleanup_failed = True
                    try:
                        process.kill()
                    except OSError:
                        pass
            try:
                process.wait(timeout=1)
            except subprocess.TimeoutExpired:
                cleanup_failed = True
            finally:
                for stream in (process.stdin, process.stdout, process.stderr):
                    if stream is not None:
                        stream.close()
            if cleanup_failed:
                raise ContractError('native runtime process cleanup failed') from None
    if process.returncode:
        raise ContractError('native runtime command failed; no authority was granted')
    if input_closed_early:
        raise ContractError('native runtime input was not fully delivered')
    return bytes(output['stdout']), bytes(output['stderr'])


@contextmanager
def _directory(directory):
    fd = None
    try:
        if sys.platform != 'darwin':
            raise ContractError('native runtime requires macOS with installed Swift tools')
        path = Path(directory)
        if path.is_symlink():
            raise ContractError('native runtime directory cannot be a symbolic link')
        path = path.resolve(strict=True)
        fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        _check_directory(path, fd)
        try:
            yield path, fd
        except OSError:
            raise ContractError('native runtime file I/O failed; retained files were not replaced') from None
    except OSError:
        raise ContractError('native runtime requires an existing private directory outside Git') from None
    finally:
        if fd is not None:
            os.close(fd)


def _check_directory(path, fd):
    info, current = os.fstat(fd), path.lstat()
    if (not stat.S_ISDIR(current.st_mode) or (info.st_dev, info.st_ino) != (current.st_dev, current.st_ino)
            or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != 0o700):
        raise ContractError('native runtime directory identity or privacy changed')
    for parent in (path, *path.parents):
        info = parent.stat()
        if (info.st_uid not in (0, os.getuid())
                or (info.st_mode & 0o022 and not (info.st_uid == 0 and info.st_mode & stat.S_ISVTX))):
            raise ContractError('native runtime parent directories must not permit other users to replace its path')
        if ((parent / '.git').exists() or (parent / '.git').is_symlink()
                or ((parent / 'HEAD').is_file() and (parent / 'objects').is_dir() and (parent / 'refs').is_dir())):
            raise ContractError('native runtime must be outside Git')


def _inventory(fd):
    names = set()
    with os.scandir(fd) as entries:
        for index, entry in enumerate(entries):
            if index >= 4:
                raise ContractError('unexpected native runtime inventory')
            names.add(entry.name)
    return names


def _read(fd, name, mode, limit):
    descriptor = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
    with os.fdopen(descriptor, 'rb') as stream:
        before = os.fstat(stream.fileno())
        if (not stat.S_ISREG(before.st_mode) or before.st_uid != os.getuid() or before.st_nlink != 1
                or stat.S_IMODE(before.st_mode) != mode or not 0 < before.st_size <= limit):
            raise ContractError('native runtime files must be bounded private regular files')
        raw = stream.read(limit + 1)
        after = os.fstat(stream.fileno())
        current = os.stat(name, dir_fd=fd, follow_symlinks=False)
        identity = lambda item: (item.st_dev, item.st_ino, item.st_size, item.st_mtime_ns, item.st_ctime_ns)
        if len(raw) != before.st_size or identity(before) != identity(after) or identity(after) != identity(current):
            raise ContractError('native runtime file changed during read')
        return raw


def _create(fd, name, raw, mode):
    descriptor = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode, dir_fd=fd)
    with os.fdopen(descriptor, 'wb') as stream:
        os.fchmod(stream.fileno(), mode)
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())


def _code_hash(path, role, *, expected=None, temporary=None):
    requirement = 'identifier "' + _identifier(role) + '"'
    if expected is not None:
        requirement += ' and cdhash H"' + expected + '"'
    _run(['/usr/bin/codesign', '--verify', '--strict', '-R=' + requirement, str(path)], cwd=path.parent, temporary=temporary)
    _, information = _run(['/usr/bin/codesign', '-d', '--verbose=4', str(path)], cwd=path.parent, temporary=temporary)
    matches = re.findall(rb'^CDHash=([0-9a-f]{40})$', information, re.MULTILINE)
    flags = re.findall(rb'^CodeDirectory .* flags=0x([0-9a-f]+)', information, re.MULTILINE)
    if len(matches) != 1 or len(flags) != 1 or not int(flags[0], 16) & 0x10000:
        raise ContractError('native runtime requires an exact hardened code signature')
    actual = matches[0].decode('ascii')
    if expected is not None and actual != expected:
        raise ContractError('native runtime code identity changed')
    return actual


def build_runtime(directory):
    """Build only into an empty owned directory; return an independent pin.

    Failed/interrupted builds may retain incomplete files. Never overwrite or
    automatically delete them; build again in another empty directory.
    """
    with _directory(directory) as (path, fd):
        if _inventory(fd):
            raise ContractError('native runtime build requires an empty directory')
        # Exclusive reservation before invoking tools; a second build cannot join.
        marker = os.open('runtime.json', os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                         0o600, dir_fd=fd)
        with os.fdopen(marker, 'wb') as manifest_file:
            os.fchmod(manifest_file.fileno(), 0o600)
            source = _source_bytes()
            manifest = {'schema': 'claimbranch.mac-runtime-build/v1', 'source_sha256': _hash(source),
                        'authorization_verified': False, 'protected_acceptance_available': False}
            with tempfile.TemporaryDirectory(prefix='claimbranch-native-build-') as temporary:
                staging = Path(temporary).resolve()
                with _directory(staging):
                    pass
                swift = staging / 'main.swift'
                swift.write_bytes(source)
                for role in ROLES:
                    binary = staging / role
                    _run(['/usr/bin/xcrun', 'swiftc', '-D', 'CLAIMBRANCH_' + role.upper(),
                          '-module-cache-path', str(staging / 'cache'), str(swift), '-o', str(binary)],
                         cwd=staging, timeout=90, temporary=staging)
                    _run(['/usr/bin/codesign', '--force', '--sign', '-', '--options', 'runtime',
                          '--identifier', _identifier(role), str(binary)], cwd=staging, temporary=staging)
                    code_hash = _code_hash(binary, role, temporary=staging)
                    raw = binary.read_bytes()
                    if not 0 < len(raw) <= MAX_BINARY:
                        raise ContractError('native runtime binary exceeds its bound')
                    _check_directory(path, fd)
                    _create(fd, role, raw, 0o700)
                    manifest[role] = {'binary_sha256': _hash(raw), 'code_hash': code_hash}
            _check_directory(path, fd)
            if _inventory(fd) != {'runtime.json', *ROLES}:
                raise ContractError('native runtime inventory changed while building')
            manifest_file.write(canonical_bytes(manifest))
            manifest_file.flush()
            os.fsync(manifest_file.fileno())
            os.fsync(fd)
        pin = _hash(canonical_bytes(manifest))
        check_runtime(path, pin)
        return pin


def check_runtime(directory, expected_build):
    """Read-only preflight. A caller-supplied pin establishes no human authority."""
    digest_text(expected_build)
    with _directory(directory) as (path, fd):
        def validate():
            _check_directory(path, fd)
            if _inventory(fd) != {'runtime.json', *ROLES}:
                raise ContractError('native runtime is incomplete or has unexpected files')
            raw = _read(fd, 'runtime.json', 0o600, 8192)
            if _hash(raw) != expected_build:
                raise ContractError('native runtime build pin does not match')
            value = normalize(decode(raw), MANIFEST)
            if canonical_bytes(value) != raw:
                raise ContractError('native runtime manifest requires canonical bytes')
            if value['source_sha256'] != _hash(_source_bytes()):
                raise ContractError('native runtime was built from different packaged source; rebuild in a new empty directory')
            for role in ROLES:
                if _hash(_read(fd, role, 0o700, MAX_BINARY)) != value[role]['binary_sha256']:
                    raise ContractError('native runtime executable differs from the pinned build')
            return value
        manifest = validate()
        results = {}
        for role in ROLES:
            _code_hash(path / role, role, expected=manifest[role]['code_hash'])
            validate()
            raw, _ = _run([str(path / role), 'check'], cwd=path, timeout=5, limit=4096)
            expected = {'schema': 'claimbranch.native-runtime-check/v1', 'role': role,
                        'identifier': _identifier(role), 'code_hash': manifest[role]['code_hash'],
                        'running_hardened': True, 'authorization_verified': False,
                        'protected_acceptance_available': False}
            if canonical_bytes(decode(raw)) != canonical_bytes(expected):
                raise ContractError('running native runtime identity does not match its build')
            results[role] = expected
        validate()
        return {'build_pin': expected_build, 'roles': results, 'authorization_verified': False,
                'protected_acceptance_available': False}


def add_runtime_commands(commands):
    runtime = commands.add_parser('runtime', help='Explicit Mac build/preflight; research approval stays unavailable')
    actions = runtime.add_subparsers(dest='runtime_action', required=True)
    for action in ('build', 'check'):
        command = actions.add_parser(action)
        command.add_argument('--directory', required=True, help='Existing private directory outside Git')
        command.add_argument('--json', action='store_true')
        if action == 'check':
            command.add_argument('--expected-build', required=True, help='Separately retained build pin, not a secret')


def _source_bytes():
    if SOURCE.is_symlink() or not SOURCE.is_file() or SOURCE.stat().st_size > 65536:
        raise ContractError('packaged native runtime source is unavailable')
    with SOURCE.open('rb') as stream:
        raw = stream.read(65537)
    if not 0 < len(raw) <= 65536:
        raise ContractError('packaged native runtime source exceeds its bound')
    for name, marker in (('Enrollment.swift', b'// CLAIMBRANCH_ENROLLMENT_SUPPORT'),
                         ('InitialSource.swift', b'// CLAIMBRANCH_INITIAL_SOURCE_SUPPORT')):
        support = SOURCE.with_name(name)
        if support.is_symlink() or not support.is_file() or not 0 < support.stat().st_size <= 65536:
            raise ContractError('packaged native support source is unavailable')
        extra = support.read_bytes()
        if not 0 < len(extra) <= 65536 or raw.count(marker) != 1:
            raise ContractError('native support source boundary or bound is invalid')
        raw = raw.replace(marker, extra)
    return raw


def run_runtime_command(args):
    import json
    completed = False
    try:
        if args.runtime_action == 'build':
            pin = build_runtime(args.directory)
            value = {'status': 'built', 'build_pin': pin, 'authorization_verified': False,
                     'protected_acceptance_available': False}
        else:
            value = {'status': 'checked', **check_runtime(args.directory, args.expected_build)}
        completed = True
        if args.json:
            print(json.dumps(value, sort_keys=True), flush=True)
        else:
            print('네이티브 실행 파일 빌드·검사 완료. 연구 승인은 아직 사용할 수 없습니다.', flush=True)
            print('재개 검사에 별도로 보관할 빌드 식별값: ' + value['build_pin'], flush=True)
        return 0
    except KeyboardInterrupt:
        code, message = 130, 'Native runtime operation interrupted; retained files were not deleted.'
    except (ContractError, OSError, ValueError) as error:
        code = 1
        message = ('Native runtime output failed after completion; the build was retained. '
                   'If its pin was not delivered, rebuild in a new empty directory.' if completed else
                   _diagnostic(error))
        if completed:
            try:
                sys.stdout.close()
            except (OSError, ValueError):
                pass
    try:
        print(message, file=sys.stderr, flush=True)
    except (OSError, ValueError):
        pass
    return code


def _diagnostic(error):
    # Only known fixed descriptions may reach the CLI; arbitrary exception text
    # (including errors injected by a tool or caller) cannot expose private paths.
    known = {
        'native runtime requires macOS with installed Swift tools': 'unsupported-host',
        'native runtime requires an existing private directory outside Git': 'unsafe-directory',
        'native runtime parent directories must not permit other users to replace its path': 'unsafe-parent',
        'native runtime must be outside Git': 'in-git',
        'native runtime build requires an empty directory': 'existing-build',
        'native runtime build pin does not match': 'pin-mismatch',
        'native runtime executable differs from the pinned build': 'changed-executable',
        'native runtime was built from different packaged source; rebuild in a new empty directory': 'changed-source',
        'native runtime is incomplete or has unexpected files': 'incomplete-build',
        'native runtime command timed out': 'timeout',
        'native runtime output exceeds its bound': 'output-limit',
        'native runtime command is unavailable': 'tool-unavailable',
        'native runtime command failed; no authority was granted': 'tool-failed',
        'native runtime file I/O failed; retained files were not replaced': 'file-io',
        'native runtime files must be bounded private regular files': 'unsafe-file',
    }
    message = str(error)
    if type(error) is ContractError and message in known:
        return 'runtime-' + known[message] + ': ' + message + '. No research approval occurred.'
    return 'runtime-failed: native runtime build/check failed; existing files were retained. No research approval occurred.'
