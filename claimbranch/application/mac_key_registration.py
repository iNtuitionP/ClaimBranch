"""Project/build-bound device-key preparation, not trusted product enrollment.

Explicit native review creates only a new synthetic key candidate. Existing
credentials, accepted research, recovery authority and TUI state are untouched.
The separately retained registration digest is an integrity input, not a receipt.
"""
import base64
import copy
from dataclasses import dataclass
import hashlib
import os
from pathlib import Path
import secrets
import stat

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest_text
from claimbranch.core.research_schema import HASH, ID, normalize, obj
from .mac_runtime import ENTRY, _check_directory, _directory, _inventory, _read, _run, check_runtime


NAME = 'key-registration.json'
REQUEST = obj(schema={'const': 'claimbranch.key-preparation/v1'}, project_id=ID,
              build_pin=HASH, broker_code_hash=ENTRY['properties']['code_hash'],
              gateway_code_hash=ENTRY['properties']['code_hash'], nonce=HASH,
              directory_identity={'type': 'string', 'minLength': 3, 'maxLength': 64,
                                  'pattern': '^[0-9]+:[0-9]+$'})
BODY = obj(schema={'const': 'claimbranch.key-registration-body/v1'}, request=REQUEST,
           public_key_x963={'type': 'string', 'minLength': 88, 'maxLength': 88}, representation_digest=HASH)
RECORD = obj(schema={'const': 'claimbranch.key-registration/v1'}, body=BODY,
             representation={'type': 'string', 'minLength': 4, 'maxLength': 10924},
             signature_der={'type': 'string', 'minLength': 12, 'maxLength': 96},
             authority={'const': 'unaccepted-key-registration'})


def key_registration_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:key-registration:v1',
            '$comment': 'Generated by scripts/export_research_schema.py. Unaccepted synthetic key candidate only; '
                        'runtime also checks canonical bytes, signatures, private files and actual device key.',
            **copy.deepcopy(RECORD)}


def _hash(raw):
    return hashlib.sha256(raw).hexdigest()


def _request(raw):
    value = normalize(decode(raw), REQUEST)
    if canonical_bytes(value) != raw:
        raise ContractError('key preparation requires exact canonical bytes')
    return value


def _identity(fd):
    info = os.fstat(fd)
    return str(info.st_dev) + ':' + str(info.st_ino)


@dataclass(frozen=True)
class KeyPreparation:
    payload: bytes
    digest: str

    def display(self):
        value = _request(self.payload)
        if _hash(self.payload) != self.digest:
            raise ContractError('key preparation digest changed')
        return {**value, 'request_digest': self.digest, 'authorization_verified': False,
                'product_custody_verified': False, 'effect': 'prepare-new-device-key-only'}


def preview_key_preparation(runtime, expected_build, directory, *, project_id):
    checked = check_runtime(runtime, expected_build)
    with _directory(directory) as (_, fd):
        if _inventory(fd):
            raise ContractError('key preparation requires a fresh empty private directory')
        value = normalize({'schema': 'claimbranch.key-preparation/v1', 'project_id': project_id,
            'build_pin': expected_build, 'broker_code_hash': checked['roles']['broker']['code_hash'],
            'gateway_code_hash': checked['roles']['gateway']['code_hash'], 'nonce': secrets.token_hex(32),
            'directory_identity': _identity(fd)}, REQUEST)
        raw = canonical_bytes(value)
        return KeyPreparation(raw, _hash(raw))


def _current(value, checked, fd):
    if (value['build_pin'] != checked['build_pin'] or value['directory_identity'] != _identity(fd)
            or any(value[role + '_code_hash'] != checked['roles'][role]['code_hash'] for role in ('broker', 'gateway'))):
        raise ContractError('key preparation runtime or destination changed')


def _result(raw, request_digest, statuses):
    value = decode(raw)
    common = {'schema', 'status', 'request_digest', 'authorization_verified', 'product_custody_verified'}
    if type(value) is not dict or value.get('status') not in statuses:
        raise ContractError('invalid native key preparation result')
    extra = {'registration_digest', 'public_key_digest'} if value['status'] in ('prepared', 'reopened') else {'stop_source'}
    if value['status'] == 'reopened': extra.add('noninteractive_signing_denied')
    if (set(value) != common | extra or value['schema'] != 'claimbranch.key-preparation-result/v1'
            or value['request_digest'] != request_digest or value['authorization_verified'] is not False
            or value['product_custody_verified'] is not False
            or ('noninteractive_signing_denied' in extra and value['noninteractive_signing_denied'] is not True)):
        raise ContractError('native key result changed its binding or authority')
    if 'stop_source' in extra:
        allowed = {'deadline'} if value['status'] == 'expired' else {'review-window', 'os-authentication'}
        if value['stop_source'] not in allowed:
            raise ContractError('native key cancellation source is missing or inconsistent')
    for field in ('request_digest', 'registration_digest', 'public_key_digest'):
        if field in value: digest_text(value[field])
    return value


def _read_registration(fd, expected):
    digest_text(expected)
    if _inventory(fd) != {NAME}:
        raise ContractError('key registration is incomplete or has unexpected files')
    raw = _read(fd, NAME, 0o600, 24576)
    if _hash(raw) != expected:
        raise ContractError('key registration differs from the separately retained digest')
    value = normalize(decode(raw), RECORD)
    if canonical_bytes(value) != raw:
        raise ContractError('key registration requires canonical bytes')
    for text, minimum, maximum in [(value['representation'], 1, 8192),
        (value['signature_der'], 8, 72), (value['body']['public_key_x963'], 65, 65)]:
        try:
            data = base64.b64decode(text, validate=True)
        except (ValueError, UnicodeError):
            raise ContractError('invalid encoded key material') from None
        if not minimum <= len(data) <= maximum or base64.b64encode(data).decode('ascii') != text:
            raise ContractError('noncanonical or oversized key material')
    public = base64.b64decode(value['body']['public_key_x963'])
    if public[0] != 4 or _hash(base64.b64decode(value['representation'])) != value['body']['representation_digest']:
        raise ContractError('key representation or public identity changed')
    return value


def _empty_reservation(fd):
    names = _inventory(fd)
    if not names:
        return
    if names != {NAME}:
        raise ContractError('unexpected key reservation retained; inspect and use a fresh directory')
    descriptor = os.open(NAME, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
    try:
        info = os.fstat(descriptor)
        current = os.stat(NAME, dir_fd=fd, follow_symlinks=False)
        if (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_uid != os.getuid()
                or stat.S_IMODE(info.st_mode) != 0o600 or info.st_size != 0 or info != current):
            raise ContractError('nonempty or unsafe key reservation retained; inspect and use a fresh directory')
    finally:
        os.close(descriptor)


def prepare_key(runtime, expected_build, directory, preparation):
    """Open explicit native preparation; cancellation grants nothing.

    A failed/cancelled/interrupted run may leave an empty reservation. Preserve
    it and retry in a new empty directory; never overwrite or auto-clean it.
    """
    if type(preparation) is not KeyPreparation:
        raise ContractError('typed key preparation required')
    preparation.display()
    request = _request(preparation.payload)
    checked = check_runtime(runtime, expected_build)
    with _directory(directory) as (path, fd):
        _current(request, checked, fd)
        if _inventory(fd):
            raise ContractError('key preparation requires a fresh empty private directory')
        output, errors = _run([str(Path(runtime).resolve() / 'broker'), 'prepare-key'], cwd=path,
                             input_bytes=preparation.payload, timeout=100, limit=4096)
        if errors: raise ContractError('native key preparation failed')
        result = _result(output, preparation.digest, {'prepared', 'cancelled', 'expired'})
        _check_directory(path, fd)
        check_runtime(runtime, expected_build)
        if result['status'] == 'prepared':
            record = _read_registration(fd, result['registration_digest'])
            public = base64.b64decode(record['body']['public_key_x963'])
            if record['body']['request'] != request or _hash(public) != result['public_key_digest']:
                raise ContractError('prepared key differs from the displayed request')
        else:
            _empty_reservation(fd)
        return result


def reopen_key(runtime, expected_build, directory, expected_registration, *, project_id):
    """Read-only actual device reconstruction and noninteractive signing denial."""
    checked = check_runtime(runtime, expected_build)
    with _directory(directory) as (path, fd):
        record = _read_registration(fd, expected_registration)
        request = record['body']['request']
        if request['project_id'] != project_id:
            raise ContractError('key registration belongs to a different project')
        _current(request, checked, fd)
        output, errors = _run([str(Path(runtime).resolve() / 'broker'), 'reopen-key', expected_registration],
                             cwd=path, input_bytes=canonical_bytes(request), timeout=15, limit=4096)
        if errors: raise ContractError('native key reopening failed')
        result = _result(output, _hash(canonical_bytes(request)), {'reopened'})
        if (result['registration_digest'] != expected_registration
                or result['public_key_digest'] != _hash(base64.b64decode(record['body']['public_key_x963']))):
            raise ContractError('reopened key identity changed')
        _check_directory(path, fd)
        _read_registration(fd, expected_registration)
        check_runtime(runtime, expected_build)
        return result
