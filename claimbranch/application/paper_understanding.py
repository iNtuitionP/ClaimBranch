"""Context-bound unfinished explanation; no acceptance, storage or AI grading.

Serialized drafts are untrusted, unaccepted text. Source context and topics are
reconstructed from the owned candidate history, never from a saved graph or a
caller claiming authority. The UI owns its editor buffers and keep/undo flow.
"""
from copy import deepcopy
from threading import RLock

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest, digest_text, identifier
from claimbranch.core.research_history import ResearchHistory
from claimbranch.core.research_schema import HASH, ID, TEXT, array, normalize, obj
from .paper_service import PaperService


RULES = "claimbranch.understanding-topics/v1"
DRAFT_MAX_BYTES = 65536
ENTRY = obj(topic_id=ID, text={**TEXT, "minLength": 0}, reuse_rationale={"enum": [False, True]})
DRAFT = obj(schema={"const": "claimbranch.paper-understanding-draft/v1"}, project_id=ID, work_id=ID,
            cause_episode_id=ID, cause_operation_id=ID, cause_digest=HASH,
            rules_version={"const": RULES}, topics_digest=HASH,
            bound_operation_id=ID, context_digest=HASH,
            revision={"type": "integer", "minimum": 0, "maximum": 2**53 - 1},
            entries=array(ENTRY, 3, 1, unique=True), authority={"const": "unaccepted-draft"},
            authorization_verified={"const": False})


def draft_schema():
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "urn:claimbranch:paper-understanding-draft:v1",
            "$comment": ("Generated by python -m scripts.export_research_schema. Unaccepted in-memory draft; no custody or authority. "
                         "Runtime also requires canonical NFC UTF-8 JSON bytes at most 65536 bytes including JSON escaping, "
                         "unique topic IDs in the exact owned order, and cause/topic/context bindings reconstructed from history. "
                         "JSON Schema alone does not verify those source bindings."),
            **deepcopy(DRAFT)}


def contextual_topics(context):
    work, original = context["work"], context["original"]
    nodes = {node["id"]: node for node in original["nodes"]}
    selection = work["selection"]
    included = set(selection["selected"]) | set(selection["required"])
    referenced = included | set(selection["existing_references"]) | set(selection["evidence_references"])
    edges = [edge for edge in original["relations"] if edge["scientific"] and edge["record_id"] in included]
    referenced.update(edge["source_id"] for edge in edges)
    topics = []

    def add(kind, prompt, node_ids, relation_ids=()):
        if not node_ids:
            return
        value = {"kind": kind, "prompt": prompt, "node_ids": sorted(node_ids),
                 "relation_ids": sorted(relation_ids), "cause_digest": original["digest"],
                 "rules_version": RULES}
        topics.append({"id": "topic-" + digest(value), **value})

    add("claim-scope", "Which part of these claims does the judgment address, and which conditions limit that conclusion?",
        set(work["potentially_affected_claim_ids"]), {edge["record_id"] for edge in edges})
    evidence = {key for key in referenced if key in nodes and nodes[key]["kind"] in ("observation", "interpretation")}
    add("evidence-interpretation", "Which referenced observations support the judgment, and what remains interpretation or uncertainty?",
        evidence, {edge["record_id"] for edge in edges if edge["source_id"] in evidence})
    plans = {key for key in included if key in nodes and nodes[key]["kind"] == "experiment-plan"}
    if plans:
        add("followup-experiment", "What possible result of these unrun experiments would change the claim or distinguish interpretations?",
            plans | {nodes[key]["content"]["claim_id"] for key in plans})
    else:
        add("manuscript-consequence", "Which manuscript claim should reflect this judgment? Exact wording requires the manuscript source.",
            set(work["potentially_affected_anchor_ids"]))
    if not 1 <= len(topics) <= 3:
        raise ContractError("conditional explanation requires a bounded causal topic")
    return topics


def _encode(value):
    raw = canonical_bytes(normalize(value, DRAFT))
    if len(raw) > DRAFT_MAX_BYTES:
        raise ContractError("explanation draft exceeds its 64 KiB limit")
    return raw


def _last_operation(history):
    from .paper_storage_codec import decode as storage_decode
    return storage_decode(history.commands[-1])["id"]


class PaperUnderstandingSession:
    def __init__(self, history, *, project_id, work_id, draft=None):
        self._initialize(PaperService(history), project_id=project_id, work_id=work_id, draft=draft)

    @staticmethod
    def restore_many(history, *, project_id, drafts):
        """Validate bounded saved drafts with locally owned source services.

        Current and earlier source services are owned only by this call. Each
        session owns its writing and detached contexts; no service escapes.
        This batch entry requires the exact ResearchHistory type.
        """
        if type(history) is not ResearchHistory or type(drafts) not in (tuple, list) or len(drafts) > 16:
            raise ContractError('bounded explanation drafts and exact research history required')
        service = PaperService(history)
        basis_services = {}
        sessions, seen = [], set()
        for raw in drafts:
            if type(raw) is not bytes or len(raw) > DRAFT_MAX_BYTES:
                raise ContractError('bounded canonical explanation draft bytes required')
            value = normalize(decode(raw), DRAFT)
            key = value['work_id']
            if key in seen:
                raise ContractError('duplicate explanation work')
            seen.add(key)
            session = PaperUnderstandingSession.__new__(PaperUnderstandingSession)
            session._initialize(service, project_id=project_id, work_id=key, draft=raw,
                                basis_services=basis_services)
            sessions.append(session)
        return sessions

    def _initialize(self, service, *, project_id, work_id, draft, basis_services=None):
        history = service._history
        context = service.understanding_return(work_id, project_id=project_id)
        topics = contextual_topics(context)
        work = context["work"]
        identity = {"project_id": project_id, "work_id": work_id,
                    "cause_episode_id": work["episode_id"], "cause_operation_id": work["cause_operation_id"],
                    "cause_digest": context["original"]["digest"], "rules_version": RULES,
                    "topics_digest": digest(topics)}
        if draft is None:
            raw = _encode({"schema": "claimbranch.paper-understanding-draft/v1", **identity,
                           "bound_operation_id": _last_operation(history), "context_digest": context["digest"],
                           "revision": 0, "entries": [{"topic_id": topic["id"], "text": "", "reuse_rationale": False}
                                                      for topic in topics],
                           "authority": "unaccepted-draft", "authorization_verified": False})
            bound = context
        else:
            if type(draft) is not bytes or len(draft) > DRAFT_MAX_BYTES:
                raise ContractError("bounded canonical explanation draft bytes required")
            value = normalize(decode(draft), DRAFT)
            raw = _encode(value)
            if raw != draft:
                raise ContractError("explanation draft must use canonical bytes")
            if any(value[key] != expected for key, expected in identity.items()):
                raise ContractError("explanation draft belongs to another cause, work or topic contract")
            if [entry["topic_id"] for entry in value["entries"]] != [topic["id"] for topic in topics]:
                raise ContractError("explanation entries must match the exact owned topics")
            position = next((i for i, cmd in enumerate(history.commands)
                             if decode(cmd)["id"] == value["bound_operation_id"]), None)
            if position is None:
                raise ContractError("explanation draft context is absent from this history")
            if type(history) is ResearchHistory and position == len(history.commands) - 1:
                # The exact current history was already reconstructed above.
                # Reuse only within this validation. Both paths still check
                # each draft's saved digest.
                bound = context
            else:
                count = position + 1
                basis_service = None if basis_services is None else basis_services.get(count)
                if basis_service is None:
                    prefix = ResearchHistory(history.seed, history.commands[:count])
                    basis_service = PaperService(prefix)
                    if basis_services is not None:
                        # The batch owns one exact history, so a prefix length
                        # identifies its bytes. Nothing is retained on sessions.
                        basis_services[count] = basis_service
                bound = basis_service.understanding_return(work_id, project_id=project_id)
            if bound["digest"] != value["context_digest"]:
                raise ContractError("explanation draft context fingerprint does not match history")
        self._history, self._project, self._work_id = history, project_id, work_id
        self._context, self._bound, self._topics, self._raw = context, bound, topics, raw
        self._lock = RLock()

    def state(self):
        with self._lock:
            value = decode(self._raw)
            # Full read views are independently bounded. They are not re-encoded
            # together as one storage record; the draft contains only bindings.
            return deepcopy({"schema": "claimbranch.paper-understanding-session/v1",
                "context": self._context, "draft_basis": self._bound["current"], "topics": self._topics,
                "draft": value, "draft_digest": digest(value),
                "context_current": value["context_digest"] == self._context["digest"],
                "retention": "memory-only", "source_ai_influenced": self._context["work"]["ai_influenced"],
                "ai_available": False, "acceptance_available": False, "closure_available": False,
                "accepted_writes": 0, "accepted_debts_created": 0, "authorization_verified": False})

    def snapshot(self):
        with self._lock:
            return self._raw

    def leave_open(self):
        """Retain unfinished input on cancel/return; never mark answers complete."""
        return self.snapshot()

    def edit(self, topic_id, text, *, reuse_rationale=None):
        """Keep unfinished text in NFC; adapters should use the returned text."""
        identifier(topic_id)
        with self._lock:
            value = decode(self._raw)
            entry = next((item for item in value["entries"] if item["topic_id"] == topic_id), None)
            if entry is None:
                raise ContractError("select a topic owned by this explanation draft")
            changed = normalize({"topic_id": topic_id, "text": text,
                                 "reuse_rationale": entry["reuse_rationale"] if reuse_rationale is None else reuse_rationale}, ENTRY)
            if changed != entry:
                entry.update(changed)
                value["revision"] += 1
                self._raw = _encode(value)
            return self.state()

    def update_source(self, history):
        with self._lock:
            if (not isinstance(history, ResearchHistory) or history.seed != self._history.seed
                    or history.commands[:len(self._history.commands)] != self._history.commands):
                raise ContractError("explanation source must extend the same owned history")
            context = PaperService(history).understanding_return(self._work_id, project_id=self._project)
            if context["original"] != self._context["original"]:
                raise ContractError("the explanation cause cannot be replaced")
            self._history, self._context = history, context
            return self.state()

    def rebind_context(self, expected_context_digest):
        """Explicitly use the displayed current basis; this is not review consent."""
        digest_text(expected_context_digest)
        with self._lock:
            if expected_context_digest != self._context["digest"]:
                raise ContractError("inspect the exact current explanation context before rebinding")
            value = decode(self._raw)
            if value["context_digest"] != expected_context_digest:
                value.update(context_digest=expected_context_digest,
                             bound_operation_id=_last_operation(self._history), revision=value["revision"] + 1)
                raw = _encode(value)
                self._raw, self._bound = raw, self._context
            return self.state()
