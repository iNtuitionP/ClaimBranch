"""Native local enrollment lookup; imported files and caller pins are not roots.

The build argument verifies installed code only. Native lookup resolves its own
fixed user namespace and rechecks the registered key, peers and resource identity.
Accepted operation consumption remains a separate gateway responsibility.
"""
from pathlib import Path
from copy import deepcopy
import os
import stat

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest_text, identifier
from .mac_runtime import _run, check_runtime
from .mac_worker import check_worker, verify_resource_custody
from .mac_key_registration import _read_registration
from .mac_runtime import _directory
from claimbranch.core.research_schema import HASH, ID, normalize, obj

PATH = {'type':'string', 'minLength':1, 'maxLength':4096, 'pattern':r'^/[^\u0000]*$'}
IDENTITY = {'type':'string', 'minLength':7, 'maxLength':128, 'pattern':'^[0-9]+:[0-9]+:[0-9]+:[0-9]+$'}
CODE = {'type':'string', 'minLength':40, 'maxLength':40, 'pattern':'^[0-9a-f]{40}$'}
BINDING = obj(schema={'const':'claimbranch.local-enrollment-body/v1'}, local_id=HASH, project_id=ID,
              runtime_directory=PATH, runtime_pin=HASH, broker_hash=CODE, gateway_hash=CODE,
              worker_directory=PATH, worker_pin=HASH, worker_hash=CODE, key_directory=PATH,
              key_identity=IDENTITY, registration_digest=HASH,
              public_key_x963={'type':'string','minLength':88,'maxLength':88}, protected_identity=IDENTITY)


def enrollment_schema():
    return {'$schema':'https://json-schema.org/draft/2020-12/schema', '$id':'urn:claimbranch:local-enrollment:v1',
            '$comment':'Generated by scripts/export_research_schema.py. A signature or imported copy is not local trust. '
                       'Native foreground creation in the fixed namespace and current native resource verification are required.',
            **obj(schema={'const':'claimbranch.local-enrollment/v1'}, body=deepcopy(BINDING),
                  signature_der={'type':'string','minLength':12,'maxLength':96})}


def enroll_project(runtime, expected_build, key_directory, registration_digest, worker_directory, worker_pin, *, project_id):
    """Explicit native foreground enrollment; a fresh local resource is minted.

    Cancellation before preparation writes nothing. Interrupted preparation may
    retain an unusable reservation; it is never silently repaired or imported.
    """
    identifier(project_id)
    check_runtime(runtime, expected_build)
    check_worker(worker_directory, worker_pin)
    with _directory(key_directory) as (keys, fd):
        record = _read_registration(fd, registration_digest)
        if record['body']['request']['project_id'] != project_id:
            raise ContractError('candidate key belongs to a different project')
        request = {'schema': 'claimbranch.enrollment-request/v1', 'project_id': project_id,
                   'key_directory': str(keys), 'registration_digest': registration_digest,
                   'worker_directory': str(Path(worker_directory).resolve(strict=True)), 'worker_pin': worker_pin}
        path = Path(runtime).resolve(strict=True)
        try:
            raw, errors = _run([str(path / 'broker'), 'enroll-project'], cwd=path,
                               input_bytes=canonical_bytes(request), timeout=105, limit=65536)
        except ContractError as error:
            raise ContractError('enrollment indeterminate: publication may have occurred; inspect before retrying') from error
        value = decode(raw)
        if errors or type(value) is not dict:
            raise ContractError('native enrollment failed; inspect retained reservations')
        if value.get('status') in ('cancelled', 'expired'):
            allowed = {'os-authentication', 'review-window'} if value['status'] == 'cancelled' else {'deadline'}
            if (set(value) != {'schema', 'status', 'stop_source', 'authorization_verified', 'protected_acceptance_available'}
                    or value['schema'] != 'claimbranch.enrollment-stop/v1' or value['stop_source'] not in allowed
                    or value['authorization_verified'] is not False or value['protected_acceptance_available'] is not False):
                raise ContractError('invalid native enrollment cancellation')
            return value
        binding = value.get('binding')
        if type(binding) is not dict:
            raise ContractError('native enrollment did not return a binding')
        try:
            result = enrollment_status(runtime, expected_build, binding.get('local_id'))
        except ContractError as error:
            raise ContractError('enrollment published but verification unavailable; inspect before retrying') from error
        if (result != value or result['binding']['registration_digest'] != registration_digest
                or result['binding']['project_id'] != project_id or result['binding']['worker_pin'] != worker_pin
                or _read_registration(fd, registration_digest) != record):
            raise ContractError('enrollment differs from the prepared connection')
        return result


def enrollment_status(runtime, expected_build, local_id):
    digest_text(local_id)
    check_runtime(runtime, expected_build)
    path = Path(runtime).resolve()
    raw, errors = _run([str(path / 'broker'), 'enrollment-status', local_id], cwd=path, limit=65536)
    value = decode(raw)
    fields = {'schema', 'status', 'binding', 'registry_directory', 'entry_digest', 'enrollment_verified',
              'authorization_verified', 'protected_acceptance_available'}
    if (errors or type(value) is not dict or set(value) != fields
            or value['schema'] != 'claimbranch.enrollment-status/v1' or value['status'] != 'enrolled'
            or value['authorization_verified'] is not False or value['protected_acceptance_available'] is not False
            or value['enrollment_verified'] is not True or type(value['binding']) is not dict
            or value['binding'].get('local_id') != local_id or value['binding'].get('runtime_pin') != expected_build):
        raise ContractError('native enrollment is unavailable or inconsistent')
    digest_text(value['entry_digest'])
    binding = value['binding']
    if (normalize(binding, BINDING) != binding
            or binding['runtime_directory'] != str(path)):
        raise ContractError('native enrollment binding is invalid')
    registry = Path(value['registry_directory'])
    if binding['key_directory'] != str(registry/'keys'):
        raise ContractError('enrolled key must be retained in its native resource')
    # Native housekeeping removes only strictly named, private canaries under
    # the same lock. A killed diagnostic cannot make an otherwise valid entry
    # unusable. This never rewrites an entry, key, or protected binding.
    swept, errors = _run([str(path/'broker'), 'enrollment-sweep', local_id], cwd=path, limit=65536)
    if errors or swept != raw:
        raise ContractError('native enrollment changed before custody verification')
    import fcntl
    with _directory(registry.parent) as (_, fd):
        lock = os.open('writer.lock', os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
        try:
            info = os.fstat(lock)
            if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_nlink != 1
                    or stat.S_IMODE(info.st_mode) != 0o600 or info.st_size != 0):
                raise ContractError('enrollment coordination lock is unsafe')
            try: fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise ContractError('enrollment is busy; retry inspection') from None
            verify_resource_custody(binding['worker_directory'], binding['worker_pin'],
                                   (registry/'entry.json', registry/'keys/key-registration.json', registry/'protected/binding'))
        finally:
            os.close(lock)
    again, errors = _run([str(path/'broker'), 'enrollment-status', local_id], cwd=path, limit=65536)
    if errors or again != raw:
        raise ContractError('native enrollment changed during custody verification')
    check_runtime(runtime, expected_build)
    return value


def sign_enrolled_operation_review(runtime, expected_build, local_id, policy, review, *, current_context):
    """Native peers independently reload the local binding; no argv peer/key pins."""
    from .mac_review_signing import _sign_checked
    from .paper_review_policy import PaperReviewPolicy
    if type(policy) is not PaperReviewPolicy or not callable(current_context):
        raise ContractError('owned policy and current context reader required')
    def candidate():
        context = current_context()
        if type(context) is not dict or set(context) != {'manuscript_digest', 'session_nonce', 'now'}:
            raise ContractError('exact current context required')
        return policy.operation_candidate(review, **context)
    before = candidate()
    enrolled = enrollment_status(runtime, expected_build, local_id)
    body = enrolled['binding']
    if decode(review.payload)['operation']['project_id'] != body['project_id']:
        raise ContractError('review belongs to another enrolled project')
    try:
        result = _sign_checked(runtime, expected_build, body['key_directory'], body['registration_digest'],
                               review, enrollment=enrolled)
    except OSError:
        raise ContractError('enrolled signing I/O failed; no operation was accepted') from None
    if enrollment_status(runtime, expected_build, local_id) != enrolled:
        raise ContractError('enrollment changed during review')
    if result['status'] == 'signed-unaccepted-review' and candidate() != before:
        raise ContractError('research context changed during signing')
    return result


def revoke_enrollment(runtime, expected_build, local_id):
    """Explicit native presence revokes future use, preserving records and key."""
    digest_text(local_id)
    check_runtime(runtime, expected_build)
    path = Path(runtime).resolve(strict=True)
    try:
        raw, errors = _run([str(path/'broker'), 'revoke-enrollment', local_id], cwd=path, timeout=105, limit=4096)
    except ContractError as error:
        raise ContractError('revocation indeterminate: it may have committed; inspect before retrying') from error
    value = decode(raw)
    if errors or type(value) is not dict:
        raise ContractError('native revocation did not complete')
    if value.get('status') in ('cancelled', 'expired'):
        status = value['status']
        sources = {'review-window', 'os-authentication'} if status == 'cancelled' else {'deadline'}
        if (set(value) != {'schema','status','stop_source','authorization_verified','protected_acceptance_available'}
                or value['schema'] != 'claimbranch.enrollment-stop/v1' or value['stop_source'] not in sources
                or value['authorization_verified'] is not False or value['protected_acceptance_available'] is not False):
            raise ContractError('invalid native revocation cancellation')
        return value
    expected = {'schema':'claimbranch.enrollment-revoked/v1', 'status':'revoked', 'local_id':local_id,
                'authorization_verified':False, 'protected_acceptance_available':False}
    if canonical_bytes(value) != canonical_bytes(expected):
        raise ContractError('native revocation result differs from requested enrollment')
    check_runtime(runtime, expected_build)
    return value
