"""Owned exact empty-project review; never an accepted genesis or imported log.

The native gateway still needs its own protected initialization operation.
This preparation reuses the existing paper association and candidate store,
without evidence fabrication, source writes or resumed authorization.
"""
from copy import deepcopy
from dataclasses import dataclass
from threading import RLock

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest, identifier
from claimbranch.core.paper_operation import TIME, check_lifetime
from claimbranch.core.research_history import ResearchHistory
from claimbranch.core.research_schema import ID, PAPER_SERIES_SEED, normalize, obj
from .paper_work_store import PaperWork
from .project_work import AssociationPreview, PREVIEW, ProjectWork


INITIALIZATION_REVIEW = obj(
    schema={'const': 'claimbranch.project-initialization-review/v1'},
    seed=PAPER_SERIES_SEED, association=PREVIEW, initial_head=ID,
    evidence_watermark={'const': 0}, operation_count={'const': 0},
    session_nonce=ID, sealed_at=TIME, expires_at=TIME,
    authority={'const': 'unaccepted-initialization-review'},
    authorization_verified={'const': False}, acceptance_available={'const': False},
    source_fidelity_verified={'const': False})


def initialization_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:project-initialization-review:v1',
            '$comment': 'Generated by scripts/export_research_schema.py. Empty candidate only. '
                        'Runtime rederives the seed/root from owned fields, rechecks the association '
                        'and requires an owned current seal with a lifetime of at most 300 seconds. '
                        'No imported commands, evidence, receipt or acceptance. Bound 256 KiB.',
            **deepcopy(INITIALIZATION_REVIEW)}


@dataclass(frozen=True)
class ProjectInitializationReview:
    payload: bytes
    digest: str


@dataclass(frozen=True)
class ProjectInitializationCandidate:
    """Work plus reviewed destination; repeatable preparation, no authority.

    Checkpoint callers must pass association as the store's save preview.
    This result is not a single-use receipt.
    """
    project: ProjectWork
    association: AssociationPreview
    review: ProjectInitializationReview


def initialization_operation(review):
    """Derive the empty reviewed effect for attestation, never source authority."""
    if type(review) is not ProjectInitializationReview:
        raise ContractError('typed initialization review required')
    value = normalize(decode(review.payload), INITIALIZATION_REVIEW)
    if canonical_bytes(value) != review.payload or digest(value) != review.digest:
        raise ContractError('exact canonical initialization review required')
    history = ResearchHistory(canonical_bytes(value['seed']))
    if (dict(history.heads)['main'] != value['initial_head']
            or value['seed']['anchor_id'] != value['association']['source']['anchor_id']):
        raise ContractError('initialization root or source anchor changed')
    return {'action': 'initialize-project', 'project_id': value['seed']['project_id'],
            'seed': value['seed'], 'association': value['association'], 'initial_head': value['initial_head']}


class ProjectInitialization:
    """One transient preparation owner, with no accepted-state capability."""

    def __init__(self, preview, *, project_id, title, thesis_id, thesis):
        if type(preview) is not AssociationPreview:
            raise ContractError('typed association preview required')
        source = preview.recheck()['source']
        # No history parameter: an imported candidate cannot become the baseline.
        self._history = ResearchHistory.start_paper_series(
            project_id, title, thesis_id, thesis, source['anchor_id'])
        self._preview = preview
        self._review = None
        self._lock = RLock()

    def _value(self, *, session_nonce, sealed_at, expires_at):
        identifier(session_nonce)
        check_lifetime(sealed_at, expires_at, sealed_at)
        association = self._preview.recheck()
        return normalize({
            'schema': 'claimbranch.project-initialization-review/v1',
            'seed': decode(self._history.seed), 'association': association,
            'initial_head': dict(self._history.heads)['main'],
            'evidence_watermark': 0, 'operation_count': 0,
            'session_nonce': session_nonce, 'sealed_at': sealed_at, 'expires_at': expires_at,
            'authority': 'unaccepted-initialization-review', 'authorization_verified': False,
            'acceptance_available': False, 'source_fidelity_verified': False}, INITIALIZATION_REVIEW)

    def prepare_review(self, *, session_nonce, sealed_at, expires_at):
        with self._lock:
            self._review = None
            value = self._value(session_nonce=session_nonce, sealed_at=sealed_at, expires_at=expires_at)
            self._review = ProjectInitializationReview(canonical_bytes(value), digest(value))
            return self._review

    def _checked(self, review, *, session_nonce, now):
        if type(review) is not ProjectInitializationReview or review is not self._review:
            raise ContractError('current owned initialization review required; imports do not seal')
        value = normalize(decode(review.payload), INITIALIZATION_REVIEW)
        check_lifetime(value['sealed_at'], value['expires_at'], now)
        if session_nonce != value['session_nonce']:
            raise ContractError('initialization session changed; review again')
        expected = self._value(session_nonce=session_nonce, sealed_at=value['sealed_at'],
                               expires_at=value['expires_at'])
        if canonical_bytes(expected) != review.payload or digest(expected) != review.digest:
            raise ContractError('initialization fields changed; review again')
        return expected

    def restore_review(self, raw, *, session_nonce, now):
        """Compare exact bytes to a still-live owned seal; never install one."""
        with self._lock:
            if type(raw) is not bytes or self._review is None or raw != self._review.payload:
                raise ContractError('imported initialization review cannot establish a seal')
            value = normalize(decode(raw), INITIALIZATION_REVIEW)
            if canonical_bytes(value) != raw:
                raise ContractError('imported initialization review cannot establish a seal')
            self._checked(self._review, session_nonce=session_nonce, now=now)
            return self._review

    def display(self, review, *, session_nonce, now):
        with self._lock:
            value = self._checked(review, session_nonce=session_nonce, now=now)
            return {**self._preview.display(),
                    'project_id': value['seed']['project_id'], 'title': value['seed']['paper_title'],
                    'thesis_id': value['seed']['claim_id'], 'thesis': value['seed']['claim_statement'],
                    'initial_head': value['initial_head'], 'evidence_watermark': 0,
                    'operation_count': 0, 'review_digest': review.digest,
                    'sealed_at': value['sealed_at'], 'expires_at': value['expires_at'],
                    'acceptance_available': False}

    def candidate(self, review, *, session_nonce, now):
        with self._lock:
            self._checked(review, session_nonce=session_nonce, now=now)
            project = ProjectWork.create(PaperWork.create(self._history), self._preview)
            return ProjectInitializationCandidate(project, self._preview, review)
