"""Foreground signing of an exact synthetic review over private native IPC.

Observation only: caller-held build/key pins are not enrolled authority, and no
signature/receipt leaves the native channel. Protected acceptance stays disabled.
"""
from concurrent.futures import ThreadPoolExecutor
from copy import deepcopy
import hashlib
import os
from pathlib import Path
import secrets
import stat
import struct
import tempfile
import time
from threading import Event

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest
from claimbranch.core.paper_operation import REVIEW
from claimbranch.core.research_schema import HASH, normalize, obj
from .mac_runtime import _directory, _check_directory, _run, check_runtime
from .mac_key_registration import REQUEST as KEY_REQUEST, _read_registration, _current, reopen_key
from .paper_review_policy import PaperReviewPolicy
from .project_initialization import ProjectInitializationReview, initialization_operation

LIMIT = 294912
REQUEST = obj(schema={'const': 'claimbranch.review-signing-request/v1'}, key_request=KEY_REQUEST,
              registration_digest=HASH, public_key_x963={'type': 'string', 'minLength': 88, 'maxLength': 88},
              review_digest=HASH, operation_digest=HASH, nonce=HASH)


def signing_request_schema():
    return {'$schema': 'https://json-schema.org/draft/2020-12/schema',
            '$id': 'urn:claimbranch:review-signing-request:v1',
            '$comment': 'Generated by scripts/export_research_schema.py. Unaccepted native request header, '
                        'framed with a four-byte big-endian length then exact operation-review bytes. '
                        'Header <=4096 bytes, review <=262144 bytes; no authority or portable receipt.',
            **deepcopy(REQUEST)}


def sign_operation_review(runtime, expected_build, key_directory, expected_registration, policy, review, *, current_context):
    if type(policy) is not PaperReviewPolicy or not callable(current_context):
        raise ContractError('owned review policy and current context reader required')
    def current():
        context = current_context()
        if type(context) is not dict or set(context) != {'manuscript_digest', 'session_nonce', 'now'}:
            raise ContractError('exact current review context required')
        return policy.operation_candidate(review, **context)
    candidate = current()
    result = _sign(runtime, expected_build, key_directory, expected_registration, review)
    if result['status'] == 'signed-unaccepted-review' and current() != candidate:
        raise ContractError('operation review changed during native signing; no authority was granted')
    return {**result, 'review_digest': review.digest, 'operation_digest': candidate.digest,
            'authorization_verified': False, 'protected_acceptance_available': False}


def _review_operation(review):
    if type(review) is ProjectInitializationReview:
        return initialization_operation(review)
    value = normalize(decode(review.payload), REVIEW)
    if (canonical_bytes(value) != review.payload or digest(value) != review.digest
            or digest(value['operation']) != value['operation_digest']):
        raise ContractError('native signing requires the exact canonical review digest')
    return value['operation']


def _packet(record, registration_digest, review, enrollment=None):
    operation = _review_operation(review)
    if type(review) is ProjectInitializationReview and enrollment is None:
        raise ContractError('initialization signing requires native enrollment')
    request = record['body']['request']
    if request['project_id'] != operation['project_id']:
        raise ContractError('review and device key belong to different projects')
    value = normalize({'schema': 'claimbranch.review-signing-request/v1', 'key_request': request,
        'registration_digest': registration_digest, 'public_key_x963': record['body']['public_key_x963'],
        'review_digest': review.digest, 'operation_digest': digest(operation), 'nonce': secrets.token_hex(32)}, REQUEST)
    if enrollment is not None:
        value.update(schema='claimbranch.enrolled-review-signing-request/v1', local_id=enrollment['binding']['local_id'])
    header = canonical_bytes(value)
    if len(header) > 4096 or not 1 <= len(review.payload) <= 262144:
        raise ContractError('native signing request exceeds bounds')
    packet = struct.pack('>I', len(header)) + header + review.payload
    if len(packet) > LIMIT:
        raise ContractError('native signing packet exceeds bounds')
    return packet


def _native_result(raw, role, packet, review, enrollment=None):
    value = decode(raw)
    if type(value) is not dict:
        raise ContractError('invalid native signing result')
    status = value.get('status')
    if status not in ('signed-unaccepted-review', 'cancelled', 'expired'):
        raise ContractError('native review signing did not complete')
    wanted = {'schema': 'claimbranch.native-review-signing/v1', 'role': role,
              'status': status, 'exchange_digest': hashlib.sha256(packet).hexdigest(),
              'review_digest': review.digest, 'operation_digest': digest(_review_operation(review)),
              'peer_verified': True, 'signature_verified': status == 'signed-unaccepted-review',
              'authorization_verified': False, 'protected_acceptance_available': False}
    if status != 'signed-unaccepted-review':
        allowed = {'deadline'} if status == 'expired' else {'review-window', 'os-authentication'}
        if value.get('stop_source') not in allowed:
            raise ContractError('native signing cancellation source is invalid')
        wanted['stop_source'] = value['stop_source']
    if enrollment is not None:
        wanted.update(local_id=enrollment['binding']['local_id'], enrollment_verified=True)
    if canonical_bytes(value) != canonical_bytes(wanted):
        raise ContractError('native signing result does not match the exact request')
    return wanted


def _sign(runtime, expected_build, key_directory, expected_registration, review):
    try:
        return _sign_checked(runtime, expected_build, key_directory, expected_registration, review)
    except OSError:
        raise ContractError('native signing I/O failed; no authority was granted') from None


def _sign_checked(runtime, expected_build, key_directory, expected_registration, review, *, enrollment=None):
    checked = check_runtime(runtime, expected_build)
    path = Path(runtime).resolve(strict=True)
    with _directory(key_directory) as (key_path, key_fd):
        record = _read_registration(key_fd, expected_registration)
        if enrollment is None:
            _current(record['body']['request'], checked, key_fd)
            reopen_key(runtime, expected_build, key_path, expected_registration,
                       project_id=record['body']['request']['project_id'])
        packet = _packet(record, expected_registration, review, enrollment)
        base = os.confstr(65537)  # Darwin's per-user temporary directory.
        if not base: raise ContractError('private native temporary root is unavailable')
        with _directory(base): pass
        with tempfile.TemporaryDirectory(prefix='cb-sign-', dir=base) as temporary:
            root = Path(temporary)
            with _directory(root):
                socket_path = root / 's'
                def command(role):
                    if enrollment is not None:
                        return [str(path / role), 'receive-enrolled-review' if role == 'gateway' else 'sign-enrolled-review',
                                str(socket_path), enrollment['binding']['local_id']]
                    other = 'broker' if role == 'gateway' else 'gateway'
                    return [str(path / role), 'receive-signed-review' if role == 'gateway' else 'sign-review',
                            str(socket_path), checked['roles'][other]['code_hash']]
                with ThreadPoolExecutor(max_workers=1) as pool:
                    cancelled = Event()
                    sender_cancelled = Event()
                    receiver = pool.submit(_run, command('gateway'), cwd=root, input_bytes=packet,
                                           timeout=105, limit=4096, cancel_event=cancelled)
                    def receiver_finished(future):
                        if future.cancelled() or future.exception() is not None:
                            sender_cancelled.set()
                    receiver.add_done_callback(receiver_finished)
                    try:
                        deadline = time.monotonic() + 5
                        while True:
                            if receiver.done():
                                receiver.result()
                                raise ContractError('native signing receiver exited before review')
                            try: info = socket_path.lstat()
                            except FileNotFoundError:
                                if time.monotonic() >= deadline:
                                    raise ContractError('native signing receiver did not become ready')
                                time.sleep(.01)
                                continue
                            if (not stat.S_ISSOCK(info.st_mode) or info.st_uid != os.getuid()
                                    or stat.S_IMODE(info.st_mode) != 0o700):
                                raise ContractError('native signing socket identity changed')
                            break
                        sender = _run(command('broker'), cwd=key_path, input_bytes=packet, timeout=100, limit=4096,
                                      cancel_event=sender_cancelled)
                        received = receiver.result()
                    finally:
                        cancelled.set()
                observations = []
                for role, (output, errors) in [('broker', sender), ('gateway', received)]:
                    if errors: raise ContractError('native signing failed')
                    observations.append(_native_result(output, role, packet, review, enrollment))
                a, b = observations
                if {k:v for k,v in a.items() if k != 'role'} != {k:v for k,v in b.items() if k != 'role'}:
                    raise ContractError('native signing peers disagree')
                if socket_path.exists() or socket_path.is_symlink():
                    raise ContractError('native signing channel cleanup is incomplete')
        _check_directory(key_path, key_fd)
        if _read_registration(key_fd, expected_registration) != record:
            raise ContractError('device key changed during review')
        check_runtime(runtime, expected_build)
        return {k:v for k,v in observations[1].items() if k not in {'schema', 'role'}}
