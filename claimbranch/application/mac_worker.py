"""Source-built confined proposal-result parity; no inference or authority.

Its one stable OS-managed container is retained, contains no trusted state and
is never a destination for keys or research. This confines this component only,
not an external server or an unrestricted same-user program.
"""
from copy import deepcopy
import errno
import hashlib
import os
from pathlib import Path
import plistlib
import re
import secrets
import socket
import stat
import tempfile

from claimbranch.core.canonical import ContractError, canonical_bytes, decode, digest_text
from claimbranch.core.context import OfflineBroker, provider_result, RESULT_BYTE_LIMIT
from claimbranch.core.research_schema import HASH, normalize, obj
from .mac_runtime import _directory, _check_directory, _create, _read, _run

IDENTIFIER = 'org.claimbranch.local-proposal-worker'
ENTITLEMENTS = {'com.apple.security.app-sandbox': True}
SOURCE = Path(__file__).with_name('native') / 'ProposalWorker.swift'
EXECUTABLE = 'Worker.app/Contents/MacOS/worker'
FILES = ('Worker.app/Contents/Info.plist', EXECUTABLE, 'Worker.app/Contents/_CodeSignature/CodeResources')
DIRECTORIES = {'Worker.app', 'Worker.app/Contents', 'Worker.app/Contents/MacOS', 'Worker.app/Contents/_CodeSignature'}
MANIFEST = obj(schema={'const': 'claimbranch.proposal-worker-build/v1'}, source_sha256=HASH,
               code_hash={'type':'string','minLength':40,'maxLength':40,'pattern':'^[0-9a-f]{40}$'},
               files=obj(**{name: HASH for name in FILES}), authorization_verified={'const':False})


def worker_schema():
    return {'$schema':'https://json-schema.org/draft/2020-12/schema',
            '$id':'urn:claimbranch:proposal-worker-build:v1',
            '$comment':'Generated by scripts/export_research_schema.py. Build integrity only; no enrolled authority.',
            **deepcopy(MANIFEST)}


def _hash(raw):
    return hashlib.sha256(raw).hexdigest()


def _source():
    if SOURCE.is_symlink() or not SOURCE.is_file() or not 0 < SOURCE.stat().st_size <= 32768:
        raise ContractError('packaged proposal worker source is unavailable')
    return SOURCE.read_bytes()


def _inventory(root):
    files, directories = set(), set()
    def visit(path):
        for item in path.iterdir():
            name = item.relative_to(root).as_posix()
            info = item.lstat()
            if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != (0o700 if name in DIRECTORIES or name == EXECUTABLE else 0o600):
                raise ContractError('worker inventory must be private and owned')
            if name in DIRECTORIES and stat.S_ISDIR(info.st_mode):
                directories.add(name); visit(item)
            elif name in {*FILES, 'worker.json'} and stat.S_ISREG(info.st_mode) and info.st_nlink == 1:
                files.add(name)
            else:
                raise ContractError('worker inventory contains an unexpected or linked entry')
    visit(root)
    if files != {*FILES, 'worker.json'} or directories != DIRECTORIES:
        raise ContractError('worker runtime is incomplete')


def _signature(path, expected=None):
    requirement = 'identifier "' + IDENTIFIER + '"'
    if expected is not None: requirement += ' and cdhash H"' + expected + '"'
    _run(['/usr/bin/codesign','--verify','--strict','-R='+requirement,str(path)],cwd=path.parent)
    _, info = _run(['/usr/bin/codesign','-d','--verbose=4',str(path)],cwd=path.parent)
    codes = re.findall(rb'^CDHash=([0-9a-f]{40})$', info, re.MULTILINE)
    flags = re.findall(rb'^CodeDirectory .* flags=0x([0-9a-f]+)',info,re.MULTILINE)
    rights, _ = _run(['/usr/bin/codesign','-d','--entitlements','-','--xml',str(path)],cwd=path.parent)
    try: rights = plistlib.loads(rights)
    except (ValueError, plistlib.InvalidFileException):
        raise ContractError('worker entitlements could not be verified') from None
    if (type(rights) is not dict or set(rights) != set(ENTITLEMENTS)
            or rights['com.apple.security.app-sandbox'] is not True
            or len(codes) != 1 or len(flags) != 1 or not int(flags[0],16) & 0x10000):
        raise ContractError('worker requires exactly App Sandbox and hardened execution')
    actual = codes[0].decode('ascii')
    if expected is not None and actual != expected: raise ContractError('worker code identity changed')
    return actual


def build_worker(directory):
    """Explicit create-only build. First execution creates/reuses one OS container."""
    with _directory(directory) as (root, fd):
        if any(root.iterdir()): raise ContractError('worker build requires an empty private directory')
        _create(fd,'worker.json',b'',0o600)
        source = _source()
        with tempfile.TemporaryDirectory(prefix='claimbranch-worker-build-') as temporary:
            staging = Path(temporary).resolve()
            with _directory(staging): pass
            main = staging/'main.swift'; main.write_bytes(source)
            for name in sorted(DIRECTORIES, key=lambda x: (x.count('/'),x)):
                (root/name).mkdir(mode=0o700)
            info = {'CFBundleIdentifier':IDENTIFIER,'CFBundleExecutable':'worker',
                    'CFBundlePackageType':'APPL','CFBundleVersion':'1'}
            (root/FILES[0]).write_bytes(plistlib.dumps(info)); (root/FILES[0]).chmod(0o600)
            binary = staging/'worker'
            _run(['/usr/bin/xcrun','swiftc','-module-cache-path',str(staging/'cache'),str(main),'-o',str(binary)],
                 cwd=staging,temporary=staging,timeout=90)
            with _directory(root/'Worker.app/Contents/MacOS') as (_, executable_fd):
                _create(executable_fd,'worker',binary.read_bytes(),0o700)
            entitlement = staging/'entitlements.plist'; entitlement.write_bytes(plistlib.dumps(ENTITLEMENTS))
            _run(['/usr/bin/codesign','--force','--sign','-','--options','runtime',
                  '--identifier',IDENTIFIER,'--entitlements',str(entitlement),
                  '--requirements','=designated => identifier "'+IDENTIFIER+'"',str(root/'Worker.app')],
                 cwd=staging,temporary=staging)
        (root/FILES[2]).chmod(0o600)
        (root/'Worker.app/Contents/_CodeSignature').chmod(0o700)
        _check_directory(root,fd); _inventory(root)
        manifest = {'schema':'claimbranch.proposal-worker-build/v1','source_sha256':_hash(source),
                    'code_hash':_signature(root/'Worker.app'),
                    'files':{name:_hash(_read(fd,name,0o700 if name==EXECUTABLE else 0o600,4*1024*1024)) for name in FILES},
                    'authorization_verified':False}
        raw = canonical_bytes(normalize(manifest,MANIFEST))
        descriptor = os.open('worker.json',os.O_WRONLY|os.O_NOFOLLOW,dir_fd=fd)
        with os.fdopen(descriptor,'wb') as stream:
            stream.write(raw); stream.flush(); os.fsync(stream.fileno())
        os.fsync(fd)
        pin = _hash(raw)
    check_worker(root,pin,execute=False)
    return pin


def check_worker(directory, expected_build, *, execute=True):
    digest_text(expected_build)
    with _directory(directory) as (root,fd):
        _inventory(root)
        raw = _read(fd,'worker.json',0o600,8192)
        if _hash(raw) != expected_build: raise ContractError('worker build pin differs')
        manifest = normalize(decode(raw),MANIFEST)
        if canonical_bytes(manifest) != raw or manifest['source_sha256'] != _hash(_source()):
            raise ContractError('worker source changed; explicitly rebuild in a fresh directory')
        for name in FILES:
            if _hash(_read(fd,name,0o700 if name==EXECUTABLE else 0o600,4*1024*1024)) != manifest['files'][name]:
                raise ContractError('worker files differ from the pinned build')
        _signature(root/'Worker.app',manifest['code_hash'])
        report = {'schema':'claimbranch.proposal-worker-check/v1','identifier':IDENTIFIER,
                  'code_hash':manifest['code_hash'],'running_hardened':True,
                  'sandbox_entitled':True,'authorization_verified':False}
        if execute:
            output, errors = _run([str(root/EXECUTABLE),'check'],cwd=root,timeout=10,limit=4096)
            if errors or output != canonical_bytes(report):
                raise ContractError('proposal worker self-report differs from its pinned code')
            check_worker(root,expected_build,execute=False)
        _check_directory(root,fd)
        return report if execute else manifest


def inspect_result(directory, expected_build, raw, *, cancel_event=None):
    """Check parent-canonicalized response parity in the confined component."""
    expected = provider_result(raw)
    # The worker receives canonical finite JSON, not a permissive parser dialect.
    payload = canonical_bytes(expected)
    check_worker(directory,expected_build,execute=False)
    root = Path(directory).resolve(strict=True)
    output, errors = _run([str(root/EXECUTABLE),'result'],cwd=root,input_bytes=payload,
                         timeout=10,limit=RESULT_BYTE_LIMIT+1024,cancel_event=cancel_event)
    wanted = {'schema':'claimbranch.proposal-worker-result/v1','input_digest':_hash(payload),
              'result':expected,'authorization_verified':False}
    if errors or output != canonical_bytes(wanted):
        raise ContractError('proposal worker returned an inconsistent result')
    check_worker(root,expected_build,execute=False)
    return expected


def complete_proposal(directory, expected_build, broker, request_id, raw, *, cancel_event=None):
    """Complete an already dispatched offline request; preserve its raw trace.

    The first arrival is claimed before worker execution. Failure or cancellation
    retains its exact trace and consumes the dispatch; another attempt needs new
    consent. No live endpoint or human consent is inferred here.
    """
    if type(broker) is not OfflineBroker: raise ContractError('owned offline broker required')
    def check():
        if cancel_event is not None and cancel_event.is_set(): raise ContractError('proposal worker cancelled')
        inspect_result(directory,expected_build,raw,cancel_event=cancel_event)
        if cancel_event is not None and cancel_event.is_set(): raise ContractError('proposal worker cancelled')
    return broker.complete_checked(request_id,raw,check=check)


def verify_boundary(directory, expected_build):
    """Observe this exact worker against new synthetic resources only.

    A writable own container is intentional. It holds no trusted keys/records;
    this measurement does not prove confinement of any external provider.
    """
    check_worker(directory,expected_build)
    base = os.confstr(65537)
    if not base: raise ContractError('private worker temporary root is unavailable')
    with _directory(base): pass
    with tempfile.TemporaryDirectory(prefix='cb-w-',dir=base) as temporary:
        root = Path(temporary)
        with _directory(root) as (_,fd):
            names = ('research','key','manuscript')
            before = {name: b'ClaimBranch synthetic '+name.encode()+b'\n' for name in names}
            for name in names: _create(fd,name,before[name],0o600)
            with socket.socket(socket.AF_UNIX,socket.SOCK_STREAM) as local, socket.socket() as network:
                local.bind(str(root/'s')); (root/'s').chmod(0o700); local.listen(2)
                network.bind(('127.0.0.1',0)); network.listen(2)
                # Positive controls distinguish OS denial from missing resources.
                for name in names:
                    for flags in (os.O_RDONLY,os.O_WRONLY):
                        handle=os.open(name,flags|os.O_NOFOLLOW,dir_fd=fd); os.close(handle)
                with socket.socket(socket.AF_UNIX,socket.SOCK_STREAM) as peer:
                    peer.connect(str(root/'s')); accepted,_=local.accept(); accepted.close()
                with socket.create_connection(network.getsockname(),timeout=2):
                    accepted,_=network.accept(); accepted.close()
                nonce=secrets.token_hex(32)
                packet=canonical_bytes({'schema':'claimbranch.worker-boundary/v1','files':[str(root/name) for name in names],
                                        'socket':str(root/'s'),'port':network.getsockname()[1],'nonce':nonce})
                runtime=Path(directory).resolve(strict=True)
                output, errors=_run([str(runtime/EXECUTABLE),'boundary'],cwd=runtime,input_bytes=packet,timeout=10,limit=8192)
                value=decode(output)
                if errors or type(value) is not dict or set(value) != {'schema','nonce','files','socket','network','authorization_verified'}:
                    raise ContractError('invalid worker boundary observation')
                if (value['schema']!='claimbranch.worker-boundary-result/v1' or value['nonce']!=nonce
                        or value['authorization_verified'] is not False or type(value['files']) is not list or len(value['files'])!=3):
                    raise ContractError('worker boundary binding changed')
                attempts=[value['socket'],value['network']]
                for item in value['files']:
                    if type(item) is not dict or set(item)!={'read','write'}: raise ContractError('invalid worker file observation')
                    attempts.extend(item.values())
                for attempt in attempts:
                    if (type(attempt) is not dict or set(attempt)!={'allowed','errno'} or attempt['allowed'] is not False
                            or type(attempt['errno']) is not int or attempt['errno'] not in (errno.EPERM,errno.EACCES)):
                        raise ContractError('worker resource access was not denied by the OS')
                if any(_read(fd,name,0o600,1024)!=before[name] for name in names):
                    raise ContractError('worker changed protected synthetic bytes')
    check_worker(directory,expected_build)
    return {'status':'worker-denial-observed','build_pin':expected_build,
            'scope':'three synthetic files and AF_UNIX socket under Darwin user temp; IPv4 TCP loopback',
            'synthetic_tmp_file_rw_denied':True,'synthetic_tmp_socket_denied':True,
            'ipv4_loopback_tcp_denied':True,'synthetic_tmp_bytes_unchanged':True,
            'external_provider_isolation_verified':False,'authorization_verified':False}


def verify_resource_custody(directory, expected_build, files):
    """Measure the exact owned registry/key/resource paths; never modify their bytes.

    Create/rename controls use only fresh random canaries in the selected private
    directories. No protected file is ever read, renamed or written by the child.
    A failed denial measurement grants nothing and preserves the original files.
    """
    from contextlib import ExitStack
    if type(files) is not tuple or len(files) != 3:
        raise ContractError('three exact protected resources required')
    if len({str(Path(path).parent.resolve()) for path in files}) != 3:
        raise ContractError('custody resources require distinct directories')
    check_worker(directory, expected_build)
    nonce = secrets.token_hex(32)
    with ExitStack() as stack:
        resources = []
        for target in files:
            path = Path(target)
            parent, fd = stack.enter_context(_directory(path.parent))
            if path.is_symlink() or path.parent.resolve() != parent:
                raise ContractError('linked custody resource refused')
            before = _read(fd, path.name, 0o600, 65536)
            for flags in (os.O_RDONLY, os.O_WRONLY):
                handle = os.open(path.name, flags | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
                os.close(handle)
            with os.scandir(fd) as entries:
                next(entries, None)
            prefix = '.cb-denial-' + nonce
            names = {prefix+'-canary': b'owned denial control', prefix+'-renamed': b'owned denial control', prefix+'-created': b''}
            for name in names:
                try:
                    os.stat(name, dir_fd=fd, follow_symlinks=False)
                except FileNotFoundError:
                    continue
                raise ContractError('custody control destination already exists')
            # Only remove this attempt's bounded, singly linked canaries.
            def cleanup(fd=fd, names=names):
                for name, content in names.items():
                    try:
                        info = os.stat(name, dir_fd=fd, follow_symlinks=False)
                    except FileNotFoundError:
                        continue
                    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid()
                            or info.st_nlink != 1 or info.st_size != len(content)):
                        raise ContractError('unexpected custody canary retained')
                    handle = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
                    with os.fdopen(handle, 'rb') as stream:
                        if stream.read(128) != content:
                            raise ContractError('changed custody canary retained')
                    os.unlink(name, dir_fd=fd)
            _create(fd, prefix+'-canary', b'owned denial control', 0o600)
            stack.callback(cleanup)
            os.rename(prefix+'-canary', prefix+'-renamed', src_dir_fd=fd, dst_dir_fd=fd)
            os.rename(prefix+'-renamed', prefix+'-canary', src_dir_fd=fd, dst_dir_fd=fd)
            _create(fd, prefix+'-created', b'', 0o600)
            os.unlink(prefix+'-created', dir_fd=fd)
            resources.append((parent / path.name, fd, before))
        if len({str(path.parent) for path, _, _ in resources}) != 3:
            raise ContractError('custody resources require distinct directories')
        packet = canonical_bytes({'schema':'claimbranch.worker-custody/v1',
                                  'files':[str(path) for path, _, _ in resources], 'nonce':nonce})
        runtime = Path(directory).resolve(strict=True)
        output, errors = _run([str(runtime / EXECUTABLE), 'custody'], cwd=runtime,
                              input_bytes=packet, timeout=10, limit=8192)
        value = decode(output)
        if (errors or type(value) is not dict or set(value) != {'schema','nonce','attempts','authorization_verified'}
                or value['schema'] != 'claimbranch.worker-custody-result/v1' or value['nonce'] != nonce
                or value['authorization_verified'] is not False or type(value['attempts']) is not list
                or len(value['attempts']) != 3):
            raise ContractError('invalid resource custody observation')
        for attempts in value['attempts']:
            if type(attempts) is not dict or set(attempts) != {'read','write','create','rename','list'}:
                raise ContractError('incomplete resource custody observation')
            for observation in attempts.values():
                if (type(observation) is not dict or set(observation) != {'allowed','errno'}
                        or observation['allowed'] is not False or type(observation['errno']) is not int
                        or observation['errno'] not in (errno.EACCES, errno.EPERM)):
                    raise ContractError('worker access to an enrolled resource was not denied')
        for path, fd, before in resources:
            if _read(fd, path.name, 0o600, 65536) != before:
                raise ContractError('protected resource changed during custody verification')
    check_worker(directory, expected_build)
    return {'status':'resource-custody-denied', 'read_write_create_rename_list_denied':True,
            'protected_bytes_unchanged':True, 'authorization_verified':False}
